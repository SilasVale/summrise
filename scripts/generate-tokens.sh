#!/usr/bin/env bash
# Generate device/console/web/src/tokens.css from device/ui/src/lib.rs.
#
# The React page used to carry a hand-kept copy of the palette; sixteen of the shared names had
# already drifted. The Rust sheet is the palette; this script writes the consumer, and
# `generated_tokens_match_the_canonical_sheet` in device/console/tests/tokens.rs fails if the
# committed file is not the one this script would write.
set -euo pipefail
cd "$(dirname "$0")/.."

target=device/console/web/src/tokens.css
{
  printf '%s\n' '/* Generated by scripts/generate-tokens.sh from device/ui/src/lib.rs. Do not edit. */'
  cargo run --quiet --manifest-path device/Cargo.toml -p summrise-ui --bin print-tokens
} > "$target"
printf 'wrote %s (%s lines)\n' "$target" "$(wc -l < "$target")"
