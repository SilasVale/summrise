/// What one poll of the request file did.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum SwapPoll {
    /// No request file.
    None,
    /// A request was consumed (applied, rolled back or refused), but the child did not change.
    Handled,
    /// A transaction ran and installed a different child.
    Swapped,
}

/// The result of the shared transaction.
#[derive(Clone, Debug, PartialEq, Eq)]
enum SwapAct {
    /// The new build passed both probes and is the committed `current` generation.
    Applied,
    /// The new build failed and a trusted generation is serving again.
    RolledBack { reason: String },
}

/// A refusal before the app was touched, or a failure after the stop.
#[derive(Clone, Debug, PartialEq, Eq)]
enum SwapError {
    /// Nothing was stopped; the request can be retried.
    Refused(String),
    /// The app was stopped and could not be recovered cleanly.
    Failed(String),
}

/// Who owns the process during a transaction.
///
/// The supervisor owns one child; the operator's `--apply` owns a stopped service (or console
/// supervisor) and, while the probes run, a standalone child it must start itself. The transaction
/// below is identical for both, which is what makes `--apply` "the same swap function once".
trait SwapOwner {
    /// Stop the process that was serving before the transaction.
    fn stop_current(&mut self) -> Result<(), String>;
    /// Kill the child this transaction started (the failed candidate, or a restored one before a
    /// service replaces it).
    fn stop_started(&mut self);
    /// Start a child from `sidecar` and return its pid.
    fn start(&mut self, sidecar: &Sidecar) -> Result<u32, String>;
    /// Settle the owner after a committed or rolled-back transaction (the supervisor does nothing;
    /// `--apply` may hand the app back to the SCM).
    fn finish(&mut self, act: Finish, sidecar: &Sidecar) -> Result<(), String>;
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Finish {
    Applied,
    RolledBack,
}

/// The supervisor's owner: it keeps the app child in the supervisor's `Option<Child>` and assigns
/// every child to the kill-on-close job.
struct SupervisedOwner<'a> {
    config: &'a Config,
    job: &'a Option<ChildJob>,
    child: &'a mut Option<Child>,
}

impl SwapOwner for SupervisedOwner<'_> {
    fn stop_current(&mut self) -> Result<(), String> {
        self.stop_started();
        Ok(())
    }

    fn stop_started(&mut self) {
        stop_child(self.child);
        let _ = fs::remove_file(app_pid_file(&self.config.data));
    }

    fn start(&mut self, sidecar: &Sidecar) -> Result<u32, String> {
        let spawned = spawn_app(self.config, sidecar)
            .map_err(|error| format!("cannot spawn the app: {error}"))?;
        if let Some(job) = self.job {
            if let Err(error) = job.assign(&spawned) {
                eprintln!(
                    "launch: warning: cannot put the app in the kill-on-close job ({error}); a killed supervisor could orphan it"
                );
            }
        }
        let pid = spawned.id();
        let _ = fs::write(app_pid_file(&self.config.data), pid.to_string());
        *self.child = Some(spawned);
        Ok(pid)
    }

    fn finish(&mut self, _act: Finish, _sidecar: &Sidecar) -> Result<(), String> {
        Ok(())
    }
}

/// The operator's owner for `--apply`: stop the service / console supervisor, run the transaction
/// against a standalone child, then hand a committed app back to the SCM when one is installed.
struct ManualOwner<'a> {
    config: &'a Config,
    service: &'a Option<Service>,
    child: Option<Child>,
}

impl SwapOwner for ManualOwner<'_> {
    fn stop_current(&mut self) -> Result<(), String> {
        self.stop_started();
        stop_owner(self.config, self.service)
    }

    fn stop_started(&mut self) {
        stop_child(&mut self.child);
        let _ = fs::remove_file(app_pid_file(&self.config.data));
    }

    fn start(&mut self, sidecar: &Sidecar) -> Result<u32, String> {
        let spawned = spawn_app(self.config, sidecar)
            .map_err(|error| format!("cannot spawn the app: {error}"))?;
        let pid = spawned.id();
        let _ = fs::write(app_pid_file(&self.config.data), pid.to_string());
        self.child = Some(spawned);
        Ok(pid)
    }

    fn finish(&mut self, _act: Finish, sidecar: &Sidecar) -> Result<(), String> {
        let Some(service) = self.service else {
            // Console mode: the standalone child stays, exactly as an operator started it.
            return Ok(());
        };
        self.stop_started();
        start_service(service)?;
        let pid = wait_for_pid_file(&app_pid_file(&self.config.data), Duration::from_secs(30))
            .ok_or_else(|| "the service started but its app did not write a pid".to_string())?;
        if !wait_healthy(self.config.port, &sidecar.version, pid, HEALTH_TIMEOUT) {
            return Err(format!(
                "the service started but its app (pid {pid}) did not become healthy on version {}",
                sidecar.version
            ));
        }
        Ok(())
    }
}

/// Poll for a request and, when one is valid, run the transaction once.
fn poll_swap(config: &Config, job: &Option<ChildJob>, child: &mut Option<Child>) -> SwapPoll {
    let request_path = swap_request(&config.install);
    let request = match read_swap_request(&request_path, now_ms()) {
        SwapRequestState::Missing => return SwapPoll::None,
        SwapRequestState::Invalid(reason) => {
            return refuse_request(config, None, format!("the request is unusable: {reason}"))
        }
        SwapRequestState::TooOld { age_ms, .. } => {
            return refuse_request(
                config,
                None,
                format!(
                    "the request is {age_ms} ms old; requests older than {SWAP_REQUEST_TIMEOUT_MS} ms are discarded"
                ),
            )
        }
        SwapRequestState::Valid(request) => request,
    };

    // C1: updates are signed by the release key, not the seed/baseline key. `validate_staged_update`
    // is the one place that choice is made.
    let pair = match validate_staged_update(
        &staged_exe(&config.install),
        &staged_sidecar(&config.install),
    ) {
        Ok(pair) => pair,
        Err(reason) => return refuse_request(config, None, reason),
    };
    if pair.sidecar.version != request.version {
        return refuse_request(
            config,
            Some(&pair.sidecar.sha256),
            format!(
                "the request names version {:?}, but the staged sidecar signs {:?}",
                request.version, pair.sidecar.version
            ),
        );
    }
    if !pair.sidecar.sha256.eq_ignore_ascii_case(&request.sha256) {
        return refuse_request(
            config,
            Some(&pair.sidecar.sha256),
            format!(
                "the request names sha256 {}, but the staged sidecar signs {}",
                request.sha256, pair.sidecar.sha256
            ),
        );
    }

    // A crash after the commit but before the result was written leaves the request behind. The
    // generation is already the staged pair, so answer `applied` instead of swapping it again.
    if current_generation_is(&config.install, &pair.sidecar) {
        eprintln!(
            "launch: the staged release {} is already the current generation; recording it",
            pair.sidecar.version
        );
        publish_result(
            config,
            &SwapResult::applied(pair.sidecar.version.clone(), &pair.sidecar.sha256, now_ms()),
        );
        return SwapPoll::Handled;
    }

    // The result belongs to this request: remove the previous one before the outcome is known.
    let _ = fs::remove_file(swap_result(&config.install));

    let version = pair.sidecar.version.clone();
    let mut owner = SupervisedOwner { config, job, child };
    let outcome = run_swap(config, &pair, &mut owner);
    let at_ms = now_ms();
    let (result, poll) = match outcome {
        Ok(SwapAct::Applied) => {
            eprintln!("launch: update to {version} applied and healthy");
            (
                SwapResult::applied(version, &pair.sidecar.sha256, at_ms),
                SwapPoll::Swapped,
            )
        }
        Ok(SwapAct::RolledBack { reason }) => {
            eprintln!("launch: update to {version} rolled back: {reason}");
            (
                SwapResult::rolled_back(version, &pair.sidecar.sha256, at_ms, reason),
                SwapPoll::Swapped,
            )
        }
        Err(SwapError::Refused(reason)) => {
            eprintln!("launch: refused the update to {version}: {reason}");
            (
                SwapResult::refused_verified(&pair.sidecar.sha256, at_ms, reason),
                SwapPoll::Handled,
            )
        }
        Err(SwapError::Failed(reason)) => {
            eprintln!("launch: CRITICAL: the update to {version} failed: {reason}");
            (
                SwapResult::rolled_back(version, &pair.sidecar.sha256, at_ms, reason),
                SwapPoll::Swapped,
            )
        }
    };
    publish_result(config, &result);
    poll
}

/// Is `sidecar` already the `current` baseline generation?
fn current_generation_is(install: &Path, sidecar: &Sidecar) -> bool {
    match resolve_baseline(install) {
        BaselineChoice::Current(current) => {
            current.sidecar.version == sidecar.version
                && current.sidecar.sha256.eq_ignore_ascii_case(&sidecar.sha256)
        }
        BaselineChoice::Previous(_) | BaselineChoice::NeedsHuman(_) => false,
    }
}

/// Write the result, then remove the request. A failed result write must not leave a request behind
/// to be retried forever, so the removal happens either way and the write failure is loud.
fn publish_result(config: &Config, result: &SwapResult) {
    let result_path = swap_result(&config.install);
    if let Err(error) = write_swap_result(&result_path, result) {
        eprintln!(
            "launch: CRITICAL: cannot write {}: {error}",
            result_path.display()
        );
    }
    let request_path = swap_request(&config.install);
    if let Err(error) = fs::remove_file(&request_path) {
        if error.kind() != io::ErrorKind::NotFound {
            eprintln!(
                "launch: warning: cannot remove {}: {error}",
                request_path.display()
            );
        }
    }
}

/// Answer a request without swapping.
///
/// `sha256` is the verified staged pair's digest when validation got that far; a request that was
/// unusable before any artifact was read has none, and the result says so by omitting the field.
fn refuse_request(config: &Config, sha256: Option<&str>, reason: String) -> SwapPoll {
    eprintln!("launch: refusing the swap request: {reason}");
    let result = match sha256 {
        Some(sha256) => SwapResult::refused_verified(sha256, now_ms(), reason),
        None => SwapResult::refused(now_ms(), reason),
    };
    publish_result(config, &result);
    SwapPoll::Handled
}

/// The one swap transaction: stage `pair` as `pending`, stop the current child, install it, start a
/// child with the staged sidecar's release facts, require two matching health answers, then commit.
///
/// A failure starts a trusted generation again and returns [`SwapAct::RolledBack`]; the request is
/// still answered. `pending` is deleted on every failure path.
fn run_swap<O: SwapOwner>(
    config: &Config,
    pair: &StagedPair,
    owner: &mut O,
) -> Result<SwapAct, SwapError> {
    if let Err(error) = discard_pending(&config.install) {
        return Err(SwapError::Refused(format!(
            "cannot clear the previous pending generation: {error}"
        )));
    }
    if let Err(error) = stage_pending(&config.install, &pair.exe, &pair.sidecar) {
        let _ = discard_pending(&config.install);
        return Err(SwapError::Refused(format!(
            "cannot stage the update: {error}"
        )));
    }

    if let Err(error) = owner.stop_current() {
        let _ = discard_pending(&config.install);
        return Err(SwapError::Failed(format!(
            "cannot stop the running app: {error}"
        )));
    }

    if let Err(error) = install_pending_over_app(&config.install, &pair.sidecar) {
        return Ok(roll_back(
            config,
            owner,
            &pair.sidecar.version,
            &pair.sidecar.sha256,
            format!("cannot install the staged binary: {error}"),
        ));
    }

    let pid = match owner.start(&pair.sidecar) {
        Ok(pid) => pid,
        Err(error) => {
            return Ok(roll_back(
                config,
                owner,
                &pair.sidecar.version,
                &pair.sidecar.sha256,
                format!("cannot start the new app: {error}"),
            ))
        }
    };
    if !wait_healthy(config.port, &pair.sidecar.version, pid, HEALTH_TIMEOUT) {
        return Ok(roll_back(
            config,
            owner,
            &pair.sidecar.version,
            &pair.sidecar.sha256,
            format!(
                "the new app (pid {pid}, version {}) did not answer /api/health twice within {}s",
                pair.sidecar.version,
                HEALTH_TIMEOUT.as_secs()
            ),
        ));
    }

    if let Err(error) = commit_pending(&config.install) {
        return Ok(roll_back(
            config,
            owner,
            &pair.sidecar.version,
            &pair.sidecar.sha256,
            format!("cannot commit the baseline generation: {error}"),
        ));
    }
    if let Err(error) = owner.finish(Finish::Applied, &pair.sidecar) {
        return Err(SwapError::Failed(format!(
            "the update was committed but the owner did not settle: {error}"
        )));
    }
    Ok(SwapAct::Applied)
}

/// Kill the failed candidate, discard `pending`, restore the whole trusted pair, start it, and
/// report the rollback. Any step that cannot complete is loud but does not pretend to be success.
///
/// The rollback outcome is published **before** the restored app is started. The app reads
/// `swap.result.json` while `ensure_state` runs, and a result written after its health probes would
/// lose the race to any reader of `/api/state`: the device would answer "started <old version>" for
/// a swap that actually rolled back. The supervisor overwrites this provisional answer with the
/// final one when the transaction returns, and both name the candidate that failed.
fn roll_back<O: SwapOwner>(
    config: &Config,
    owner: &mut O,
    failed_version: &str,
    failed_sha256: &str,
    reason: String,
) -> SwapAct {
    eprintln!("launch: rolling back: {reason}");
    publish_result(
        config,
        &SwapResult::rolled_back(
            failed_version.to_owned(),
            failed_sha256,
            now_ms(),
            reason.clone(),
        ),
    );
    owner.stop_started();
    if let Err(error) = discard_pending(&config.install) {
        eprintln!("launch: warning: cannot discard the pending generation: {error}");
    }
    match start_current(config, owner) {
        Ok(baseline) => {
            if let Err(error) = owner.finish(Finish::RolledBack, &baseline.sidecar) {
                eprintln!("launch: CRITICAL: the rollback did not settle: {error}");
            }
        }
        Err(error) => {
            eprintln!("launch: CRITICAL: cannot restart a trusted generation: {error}");
        }
    }
    SwapAct::RolledBack { reason }
}

/// Restore the resolved baseline and start one child from it, waiting for its health best-effort.
fn start_current<O: SwapOwner>(config: &Config, owner: &mut O) -> Result<Baseline, String> {
    let baseline = restore_current_app(&config.install)?;
    let pid = owner.start(&baseline.sidecar)?;
    if !wait_healthy(config.port, &baseline.sidecar.version, pid, HEALTH_TIMEOUT) {
        eprintln!(
            "launch: warning: the restored app (pid {pid}, version {}) did not answer health",
            baseline.sidecar.version
        );
    }
    Ok(baseline)
}

/// `--apply <staged> <sidecar>`: the operator-only manual entry point.
///
/// The product never calls this; the app writes `swap.request.json` instead. An operator uses it
/// when no supervisor is serving (a stopped service, or a console install that is down). It runs the
/// same [`run_swap`] transaction once and leaves the device in the same generation layout.
pub fn apply(config: &Config, staged: &Path, sidecar_path: &Path) -> ExitCode {
    let pair = match validate_staged_update(staged, sidecar_path) {
        Ok(pair) => pair,
        Err(error) => return fail(&error),
    };
    // The operator is the last resort: a digest this device rolled back does not block `--apply`, but
    // it is named loudly and audited before the transaction starts. A state document that cannot be
    // read is reported too — silence would be the bypass this check exists to close (review I3).
    match summrise_launch::remembered_rollback(&config.data, &pair.sidecar.sha256) {
        Ok(Some(artifact)) => {
            eprintln!(
                "launch: warning: {} was rolled back on this device (version {}, at {} ms); \
                 --apply is an operator override and will install it anyway",
                pair.sidecar.sha256, artifact.version, artifact.at_ms
            );
            if let Err(error) = summrise_launch::append_operator_rollback_event(
                &config.data,
                &pair.sidecar.version,
                &pair.sidecar.sha256,
                artifact.at_ms,
            ) {
                // The audit is evidence, not a precondition: refusing here would make the last
                // resort unavailable exactly when the disk is the thing that is wrong. It is loud.
                eprintln!(
                    "launch: CRITICAL: the operator override of {} could not be audited: {error}",
                    pair.sidecar.sha256
                );
            }
        }
        Ok(None) => {}
        Err(error) => eprintln!(
            "launch: warning: cannot apply the rollback guard: {error}; \
             --apply is the operator's last resort and continues"
        ),
    }
    let service = match open_installed_service(
        ServiceAccess::QUERY_STATUS | ServiceAccess::STOP | ServiceAccess::START,
    ) {
        Ok(service) => service,
        Err(error) => return exit_for(Err(error)),
    };

    let mut owner = ManualOwner {
        config,
        service: &service,
        child: None,
    };
    match run_swap(config, &pair, &mut owner) {
        Ok(SwapAct::Applied) => {
            eprintln!(
                "launch: update to {} applied and healthy on port {}",
                pair.sidecar.version, config.port
            );
            ExitCode::SUCCESS
        }
        Ok(SwapAct::RolledBack { reason }) => {
            eprintln!(
                "launch: update to {} rolled back: {reason}",
                pair.sidecar.version
            );
            ExitCode::from(1)
        }
        Err(SwapError::Refused(error)) => fail(&error),
        Err(SwapError::Failed(error)) => exit_for(Err(error)),
    }
}

