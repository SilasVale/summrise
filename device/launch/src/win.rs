/// Harden `<data>` so every file written under it inherits a safe DACL.
///
/// On Windows a file's protection is its parent's inheritable ACEs unless someone replaces the child's
/// DACL. The install token, `identity.key` and `console-token.json` are all credentials written under
/// `<data>`, so the directory itself is protected with inheritable SYSTEM/Administrators ACEs before
/// any of them is created (review C1). The read-back inside `protect_dir` is what makes a failure
/// here a refusal rather than a warning.
fn protect_data_dir(data: &Path) -> Result<(), String> {
    fs::create_dir_all(data).map_err(|error| {
        format!(
            "cannot create the data directory {}: {error}",
            data.display()
        )
    })?;
    summrise_winsec::protect_dir(data).map_err(|error| {
        format!(
            "cannot protect the data directory {} ({error}); refusing to install under an \
             unprotected directory",
            data.display()
        )
    })
}

/// Mint `<data>/token` once and protect it, or leave an existing token exactly alone.
///
/// The file is the root of the `Owner` subject. It is 32 CSPRNG bytes as 64 lower-hex characters and
/// a newline, created with `create_new` so two concurrent installers cannot both mint, and its DACL
/// is replaced with a protected one that grants full control only to SYSTEM and Administrators. If
/// anything after creation fails the file is removed, because an install that leaves an unprotected
/// token behind fails the security model rather than papering over it.
///
/// `<data>` is hardened even when the token already exists: the installer is the one place that runs
/// on every install and upgrade, and the files enrollment writes later must inherit a safe DACL.
fn ensure_install_token(data: &Path) -> Result<bool, String> {
    let path = install_token(data);
    protect_data_dir(data)?;
    match token_action(path.exists()) {
        TokenAction::Keep => Ok(false),
        TokenAction::Create => {
            let mut bytes = [0u8; TOKEN_BYTES];
            random_token_bytes(&mut bytes)?;
            let text = token_text(&bytes);
            let mut file = match fs::OpenOptions::new()
                .write(true)
                .create_new(true)
                .open(&path)
            {
                Ok(file) => file,
                // Another installer won the race between `exists` and `create_new`: its token is
                // the install token, and the contract is to leave an existing token alone.
                Err(error) if error.kind() == io::ErrorKind::AlreadyExists => return Ok(false),
                Err(error) => {
                    return Err(format!("cannot create {}: {error}", path.display()));
                }
            };
            // Protect the empty file before the secret is written, so a crash can at worst leave an
            // empty protected token (a fail-closed 401), never readable key material under the
            // directory's inherited DACL.
            if let Err(error) = summrise_winsec::protect_file(&path) {
                drop(file);
                let _ = fs::remove_file(&path);
                return Err(format!(
                    "cannot protect {} ({error}); refusing to install an unprotected token",
                    path.display()
                ));
            }
            if let Err(error) = file
                .write_all(text.as_bytes())
                .and_then(|()| file.sync_all())
            {
                let _ = fs::remove_file(&path);
                return Err(format!("cannot write {}: {error}", path.display()));
            }
            drop(file);
            Ok(true)
        }
    }
}

/// 32 bytes from the OS CSPRNG. `BCryptGenRandom` with the system-preferred RNG needs no algorithm
/// handle and is the documented Win32 primitive for this.
fn random_token_bytes(bytes: &mut [u8; TOKEN_BYTES]) -> Result<(), String> {
    use windows_sys::Win32::Security::Cryptography::{
        BCryptGenRandom, BCRYPT_USE_SYSTEM_PREFERRED_RNG,
    };

    let status = unsafe {
        BCryptGenRandom(
            std::ptr::null_mut(),
            bytes.as_mut_ptr(),
            bytes.len() as u32,
            BCRYPT_USE_SYSTEM_PREFERRED_RNG,
        )
    };
    if status == 0 {
        Ok(())
    } else {
        Err(format!(
            "BCryptGenRandom failed (NTSTATUS 0x{status:08x}); refusing to mint a weak token"
        ))
    }
}

/// `--install-service`: give the install a baseline generation, create the service (or point an
/// existing one at this binary), and configure the SCM failure actions that restart a supervisor
/// which exits without being asked. Idempotent, so an installer can run it on every launch.
///
/// The baseline comes first and is a hard gate (NEW-1): a service that starts into `NeedsHuman`
/// would be an install that reported success and served nothing. If no generation can be produced
/// this returns an error before the service manager is opened, so nothing is registered or
/// reconfigured.
pub fn install(
    config: &Config,
    seed_sidecar: Option<&Path>,
    replace_baseline: bool,
) -> Result<(), String> {
    match ensure_baseline(
        &config.install,
        seed_sidecar,
        LAUNCHER_PUBKEY_HEX,
        replace_baseline,
    )? {
        BaselineInstall::Kept => {}
        BaselineInstall::Migrated => eprintln!(
            "launch: migrated the pre-generation baseline into {}",
            generation_dir(&config.install, CURRENT_DIR).display()
        ),
        BaselineInstall::Replaced => eprintln!(
            "launch: replaced baseline/current from the installer's pair; the previous generation is baseline/previous"
        ),
        BaselineInstall::Seeded => eprintln!(
            "launch: seeded {} from {} and the installer's sidecar",
            generation_dir(&config.install, CURRENT_DIR).display(),
            app_exe(&config.install).display()
        ),
    }

    match ensure_install_token(&config.data) {
        Ok(true) => eprintln!(
            "launch: minted the install token at {}",
            install_token(&config.data).display()
        ),
        Ok(false) => {}
        Err(error) => return Err(error),
    }

    let exe = std::env::current_exe()
        .map_err(|error| format!("cannot resolve the launcher's own path: {error}"))?;
    let manager = ServiceManager::local_computer(
        None::<&str>,
        ServiceManagerAccess::CONNECT | ServiceManagerAccess::CREATE_SERVICE,
    )
    .map_err(|error| format!("cannot open the service manager: {error}"))?;
    let info = service_info(config, &exe);

    let service = match manager.open_service(
        SERVICE_NAME,
        ServiceAccess::CHANGE_CONFIG | ServiceAccess::QUERY_STATUS | ServiceAccess::START,
    ) {
        Ok(service) => {
            service
                .change_config(&info)
                .map_err(|error| format!("cannot update service {SERVICE_NAME}: {error}"))?;
            service
        }
        Err(windows_service::Error::Winapi(error)) if error.raw_os_error() == Some(1060) => manager
            .create_service(
                &info,
                ServiceAccess::CHANGE_CONFIG | ServiceAccess::QUERY_STATUS | ServiceAccess::START,
            )
            .map_err(|error| format!("cannot create service {SERVICE_NAME}: {error}"))?,
        Err(error) => return Err(format!("cannot open service {SERVICE_NAME}: {error}")),
    };
    service
        .set_description(SERVICE_DESCRIPTION)
        .map_err(|error| format!("cannot describe service {SERVICE_NAME}: {error}"))?;
    set_failure_actions(&service)?;

    let status = service
        .query_status()
        .map_err(|error| format!("cannot query service {SERVICE_NAME}: {error}"))?;
    if status.current_state != ServiceState::Running {
        start_service(&service)?;
    }
    eprintln!(
        "launch: service {SERVICE_NAME} is installed for {} on port {}",
        config.install.display(),
        config.port
    );
    Ok(())
}

/// F5/I4: the SCM restarts **the supervisor** when it exits unexpectedly (three restarts, five
/// seconds apart, resetting after an hour). It does not see the app's hang: the app's watchdog exits
/// its own process after two missed health probes, and the supervisor — which owns the child — sees
/// that exit and restarts it within its own budget. The SCM's actions are the layer above: they run
/// when the supervisor itself gives up and exits nonzero, not when the app does.
fn set_failure_actions(service: &Service) -> Result<(), String> {
    let action = ServiceAction {
        action_type: ServiceActionType::Restart,
        delay: SERVICE_RESTART_DELAY,
    };
    let actions = ServiceFailureActions {
        reset_period: ServiceFailureResetPeriod::After(SERVICE_FAILURE_RESET),
        reboot_msg: None,
        command: None,
        actions: Some(vec![action; SERVICE_RESTART_COUNT]),
    };
    service
        .update_failure_actions(actions)
        .map_err(|error| format!("cannot configure failure actions for {SERVICE_NAME}: {error}"))?;
    // A supervisor that gives up reports SERVICE_STOPPED with a nonzero service exit code. Without
    // this flag the SCM treats that as a normal stop and runs no failure action, so the one failure
    // the design cares about (the app keeps failing) would leave the service down.
    if let Err(error) = service.set_failure_actions_on_non_crash_failures(true) {
        eprintln!(
            "launch: warning: cannot enable failure actions on non-crash exits for {SERVICE_NAME}: {error}"
        );
    }
    Ok(())
}

/// `--uninstall-service`: stop and delete the service. Removing one that is not there is success.
pub fn uninstall() -> Result<(), String> {
    let manager = ServiceManager::local_computer(None::<&str>, ServiceManagerAccess::CONNECT)
        .map_err(|error| format!("cannot open the service manager: {error}"))?;
    let service = match manager.open_service(
        SERVICE_NAME,
        ServiceAccess::STOP | ServiceAccess::QUERY_STATUS | ServiceAccess::DELETE,
    ) {
        Ok(service) => service,
        Err(windows_service::Error::Winapi(error)) if error.raw_os_error() == Some(1060) => {
            eprintln!("launch: service {SERVICE_NAME} is not installed");
            return Ok(());
        }
        Err(error) => return Err(format!("cannot open service {SERVICE_NAME}: {error}")),
    };
    stop_service(&service)?;
    service
        .delete()
        .map_err(|error| format!("cannot delete service {SERVICE_NAME}: {error}"))?;
    eprintln!("launch: service {SERVICE_NAME} was removed");
    Ok(())
}

fn service_info(config: &Config, exe: &Path) -> ServiceInfo {
    ServiceInfo {
        name: OsString::from(SERVICE_NAME),
        display_name: OsString::from(SERVICE_DISPLAY_NAME),
        service_type: ServiceType::OWN_PROCESS,
        start_type: ServiceStartType::AutoStart,
        error_control: ServiceErrorControl::Normal,
        executable_path: exe.to_path_buf(),
        // C3: one spelling of the service's argv, shared with the tests. `--data` is also where the
        // app looks for `console.json`, so the console link and the service cannot name two
        // directories.
        launch_arguments: service_launch_arguments(&config.install, &config.data, config.port),
        dependencies: vec![],
        account_name: None, // LocalSystem
        account_password: None,
    }
}
