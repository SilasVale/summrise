/// Stop the current app: through the SCM when the service is installed, otherwise through the pid
/// files the console supervisor writes.
fn stop_owner(config: &Config, service: &Option<Service>) -> Result<(), String> {
    match service {
        Some(service) => stop_service(service),
        None => stop_console_owner(config),
    }
}

/// Stop a console supervisor and its child.
///
/// The supervisor is stopped first: it owns the child through a kill-on-close job, so terminating
/// the supervisor is what takes the child with it. Killing the child first would only invite the
/// supervisor to restart it before the manual swap began.
fn stop_console_owner(config: &Config) -> Result<(), String> {
    let launcher_pid = read_pid(&launcher_pid_file(&config.data));
    if let Some(pid) = launcher_pid {
        if process_name(pid).is_some_and(|name| name.eq_ignore_ascii_case(LAUNCHER_EXE)) {
            terminate_verified(pid, LAUNCHER_EXE)?;
            wait_for_process_exit(pid, LAUNCHER_EXE, SUPERVISOR_EXIT_TIMEOUT)?;
        }
    }
    let app_pid = read_pid(&app_pid_file(&config.data));
    if let Some(pid) = app_pid {
        if process_name(pid).is_some_and(|name| name.eq_ignore_ascii_case(APP_EXE)) {
            terminate_verified(pid, APP_EXE)?;
        }
    }
    let _ = fs::remove_file(app_pid_file(&config.data));
    let _ = fs::remove_file(launcher_pid_file(&config.data));
    wait_for_port_free(config.port, Duration::from_secs(10))
}

fn wait_for_port_free(port: u16, timeout: Duration) -> Result<(), String> {
    let address = SocketAddr::from(([127, 0, 0, 1], port));
    let deadline = Instant::now() + timeout;
    loop {
        if TcpStream::connect_timeout(&address, Duration::from_millis(200)).is_err() {
            return Ok(());
        }
        if Instant::now() >= deadline {
            return Err(format!(
                "port {port} still answers after the previous owner was stopped"
            ));
        }
        std::thread::sleep(Duration::from_millis(100));
    }
}

fn wait_for_pid_file(path: &Path, timeout: Duration) -> Option<u32> {
    let deadline = Instant::now() + timeout;
    loop {
        if let Some(pid) = read_pid(path) {
            return Some(pid);
        }
        if Instant::now() >= deadline {
            return None;
        }
        std::thread::sleep(Duration::from_millis(100));
    }
}

fn read_pid(path: &Path) -> Option<u32> {
    fs::read_to_string(path).ok()?.trim().parse().ok()
}

fn process_name(pid: u32) -> Option<String> {
    let handle = open_process(PROCESS_QUERY_LIMITED_INFORMATION, pid)?;
    let name = image_file_name(handle);
    unsafe { CloseHandle(handle) };
    name
}

fn open_process(access: u32, pid: u32) -> Option<HANDLE> {
    let handle = unsafe { OpenProcess(access, 0, pid) };
    if handle == 0 {
        None
    } else {
        Some(handle)
    }
}

fn image_file_name(handle: HANDLE) -> Option<String> {
    let mut buffer = [0u16; 1024];
    let mut length = buffer.len() as u32;
    let ok = unsafe { QueryFullProcessImageNameW(handle, 0, buffer.as_mut_ptr(), &mut length) };
    if ok == 0 {
        return None;
    }
    let path = PathBuf::from(OsString::from_wide(&buffer[..length as usize]));
    path.file_name()
        .map(|name| name.to_string_lossy().into_owned())
}

/// Terminate `pid` only if its image is `expected`. A recycled PID must never cost the device an
/// unrelated process.
fn terminate_verified(pid: u32, expected: &str) -> Result<(), String> {
    let Some(handle) = open_process(
        PROCESS_QUERY_LIMITED_INFORMATION | PROCESS_TERMINATE | PROCESS_SYNCHRONIZE,
        pid,
    ) else {
        return Ok(()); // already gone
    };
    let name = image_file_name(handle);
    let is_ours = name
        .as_deref()
        .is_some_and(|name| name.eq_ignore_ascii_case(expected));
    if !is_ours {
        unsafe { CloseHandle(handle) };
        return Err(format!(
            "pid {pid} is not {expected} (found {}); refusing to stop it",
            name.as_deref().unwrap_or("<unreadable>")
        ));
    }
    let terminated = unsafe { TerminateProcess(handle, 1) };
    unsafe {
        WaitForSingleObject(handle, 5_000);
        CloseHandle(handle);
    }
    if terminated == 0 {
        return Err(format!(
            "TerminateProcess({pid}) failed: {}",
            io::Error::last_os_error()
        ));
    }
    Ok(())
}

fn wait_for_process_exit(pid: u32, expected: &str, timeout: Duration) -> Result<(), String> {
    let Some(handle) = open_process(PROCESS_QUERY_LIMITED_INFORMATION | PROCESS_SYNCHRONIZE, pid)
    else {
        return Ok(());
    };
    let name = image_file_name(handle);
    let is_ours = name
        .as_deref()
        .is_some_and(|name| name.eq_ignore_ascii_case(expected));
    if !is_ours {
        unsafe { CloseHandle(handle) };
        return Err(format!(
            "pid {pid} is not {expected} (found {}); refusing to wait on it",
            name.as_deref().unwrap_or("<unreadable>")
        ));
    }
    let waited = unsafe { WaitForSingleObject(handle, timeout.as_millis() as u32) };
    unsafe { CloseHandle(handle) };
    if waited == WAIT_OBJECT_0 {
        Ok(())
    } else {
        Err(format!(
            "the {expected} (pid {pid}) did not exit within {}s; the update would race it",
            timeout.as_secs()
        ))
    }
}

fn open_installed_service(access: ServiceAccess) -> Result<Option<Service>, String> {
    let manager = ServiceManager::local_computer(None::<&str>, ServiceManagerAccess::CONNECT)
        .map_err(|error| format!("cannot open the service manager: {error}"))?;
    match manager.open_service(SERVICE_NAME, access) {
        Ok(service) => Ok(Some(service)),
        Err(windows_service::Error::Winapi(error)) if error.raw_os_error() == Some(1060) => {
            Ok(None)
        }
        Err(error) => Err(format!("cannot open service {SERVICE_NAME}: {error}")),
    }
}

fn stop_service(service: &Service) -> Result<(), String> {
    let status = service
        .query_status()
        .map_err(|error| format!("cannot query service {SERVICE_NAME}: {error}"))?;
    if status.current_state == ServiceState::Stopped {
        return Ok(());
    }
    if let Err(error) = service.stop() {
        let already_stopped = matches!(
            &error,
            windows_service::Error::Winapi(io) if io.raw_os_error() == Some(1062)
        );
        if !already_stopped {
            return Err(format!("cannot stop service {SERVICE_NAME}: {error}"));
        }
    }
    wait_for_service_state(service, ServiceState::Stopped, Duration::from_secs(30))
}

fn start_service(service: &Service) -> Result<(), String> {
    let status = service
        .query_status()
        .map_err(|error| format!("cannot query service {SERVICE_NAME}: {error}"))?;
    if status.current_state == ServiceState::Running {
        return Ok(());
    }
    let no_arguments: [OsString; 0] = [];
    if let Err(error) = service.start(&no_arguments) {
        let already_running = matches!(
            &error,
            windows_service::Error::Winapi(io) if io.raw_os_error() == Some(1056)
        );
        if !already_running {
            return Err(format!("cannot start service {SERVICE_NAME}: {error}"));
        }
    }
    wait_for_service_state(service, ServiceState::Running, Duration::from_secs(30))
}

fn wait_for_service_state(
    service: &Service,
    wanted: ServiceState,
    timeout: Duration,
) -> Result<(), String> {
    let deadline = Instant::now() + timeout;
    loop {
        let status = service
            .query_status()
            .map_err(|error| format!("cannot query service {SERVICE_NAME}: {error}"))?;
        if status.current_state == wanted {
            return Ok(());
        }
        if Instant::now() >= deadline {
            return Err(format!(
                "service {SERVICE_NAME} did not reach {wanted:?} within {}s (currently {:?})",
                timeout.as_secs(),
                status.current_state
            ));
        }
        std::thread::sleep(Duration::from_millis(200));
    }
}

