/// Parse argv and dispatch one of the launcher's modes.
pub fn entry() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let Some(mode) = args.first().map(String::as_str) else {
        return usage();
    };

    match mode {
        "--self-check" => self_check(&args[1..]),
        "run" => match config_with_console(&args[1..]) {
            Ok((config, console)) => match persist_console_link(&config, console.as_ref()) {
                Ok(()) => run_console(&config),
                Err(error) => fail(&error),
            },
            Err(error) => fail(&error),
        },
        "service" => match parse_service_args(&args[1..], SERVICE_NAME) {
            Ok((name, _)) => run_service_entry(&name),
            Err(error) => fail(&error),
        },
        "--apply" => {
            let (Some(staged), Some(sidecar)) = (args.get(1), args.get(2)) else {
                eprintln!("launch: --apply needs <staged> <sidecar>");
                return usage();
            };
            let staged = absolute(Path::new(staged));
            let sidecar = absolute(Path::new(sidecar));
            match config_from_args(&args[3..]) {
                Ok(config) => apply(&config, &staged, &sidecar),
                Err(error) => fail(&error),
            }
        }
        "--install-service" => match parse_install_args(&args[1..]) {
            Ok((config, seed_sidecar, console, replace)) => {
                match persist_console_link(&config, console.as_ref()) {
                    Ok(()) => exit_for(install(&config, seed_sidecar.as_deref(), replace)),
                    Err(error) => fail(&error),
                }
            }
            Err(error) => fail(&error),
        },
        "--uninstall-service" => exit_for(uninstall()),
        "-h" | "--help" => {
            print_usage();
            ExitCode::SUCCESS
        }
        other => {
            eprintln!("launch: unknown mode {other:?}");
            usage()
        }
    }
}

/// `--self-check <install> [--data <data>]`: what the launcher can prove about this install.
///
/// Read-only and safe to run while the service runs: it opens files and hashes them, and nothing
/// else. Exit 0 when every check passes, 1 when one does not — an operator's script can branch on
/// that without parsing English.
fn self_check(args: &[String]) -> ExitCode {
    let mut install: Option<PathBuf> = None;
    let mut data: Option<PathBuf> = None;
    let mut arguments = args.iter();
    while let Some(argument) = arguments.next() {
        match argument.as_str() {
            "--install" => match arguments.next() {
                Some(value) => install = Some(PathBuf::from(value)),
                None => return self_check_usage(),
            },
            "--data" => match arguments.next() {
                Some(value) => data = Some(PathBuf::from(value)),
                None => return self_check_usage(),
            },
            other if other.starts_with("--") => return self_check_usage(),
            other => {
                if install.is_none() {
                    install = Some(PathBuf::from(other));
                } else {
                    return self_check_usage();
                }
            }
        }
    }
    let Some(install) = install else {
        return self_check_usage();
    };
    let install = absolute(&install);
    let report = summrise_launch::inspect(&install, data.as_deref());
    println!("summrise-launch self-check: {}", install.display());
    print!("{report}");
    if report.ok() {
        ExitCode::SUCCESS
    } else {
        ExitCode::from(1)
    }
}

fn self_check_usage() -> ExitCode {
    eprintln!("launch: --self-check needs <install> [--data <data>]");
    ExitCode::from(2)
}

fn usage() -> ExitCode {
    print_usage();
    ExitCode::from(2)
}

fn print_usage() {
    eprintln!(
        "\
summrise-launch — repair, supervise and swap summrise-device.exe

  summrise-launch run [--install DIR] [--data DIR] [--port N]
                      [--console-url URL --console-token-file PATH]
                      [--mesh-broker ORIGIN [--mesh-relay ADDR] [--mesh-stun ADDR]]
  summrise-launch service [--service-name NAME]
  summrise-launch --apply <staged> <sidecar> [--install DIR] [--data DIR] [--port N]
  summrise-launch --install-service [--replace-baseline] [--seed-sidecar <path>]
                      [--install DIR] [--data DIR] [--port N]
                      [--console-url URL --console-token-file PATH]
                      [--mesh-broker ORIGIN [--mesh-relay ADDR] [--mesh-stun ADDR]]
  summrise-launch --uninstall-service

The port defaults to SUMMRISE_PORT, then 18080. The install directory defaults to the launcher's
own directory, and the data directory to <install>/data. The service name defaults to SummriseLaunch;
a service registered under another name must pass that name to `service`.

--console-url/--console-token-file and --mesh-broker/--mesh-relay/--mesh-stun are persisted as
<data>/console.json for the app to read; the service argv carries none of them. A broker must be an
http://host:port origin, a relay or STUN reflector must be host:port, and either without a broker
is refused. Running without these flags leaves an existing link in place; remove the file to disarm
it.

--install-service seeds <install>/baseline/current when the tree has no baseline: it migrates the
pre-generation flat pair (baseline/summrise-device.exe + baseline/summrise-device.json), or copies
the install's summrise-device.exe with the signed sidecar named by --seed-sidecar. With neither, the
install fails and no service is registered. An existing complete current generation is left alone.

The product never runs --apply: the app writes <install>/swap.request.json and the running
supervisor performs the swap, writing <install>/swap.result.json. --apply is an operator-only manual
entry point that runs the same transaction once while no supervisor is serving. There is one
supervisor per install: a named mutex makes a second `run` (or a `run` beside the service) exit
rather than race the swap transaction.

The supervisor starts the app with --install, --data, --port, --token-file and the release facts of
the sidecar it booted: --release-version, --release-sha and --release-channel (stable or canary).
The app records those in state.json and /api/health; there is no other source for its version or
channel. The child is also marked SUMMRISE_SUPERVISED=1: only a process with a supervisor may exit
after a panel enrollment and trust that it will be brought back."
    );
}

fn fail(error: &str) -> ExitCode {
    eprintln!("launch: {error}");
    ExitCode::from(2)
}

fn exit_for(result: Result<(), String>) -> ExitCode {
    match result {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("launch: {error}");
            ExitCode::from(1)
        }
    }
}

fn config_from_args(args: &[String]) -> Result<Config, String> {
    let exe = std::env::current_exe()
        .map_err(|error| format!("cannot resolve the launcher's own path: {error}"))?;
    let default_install = exe
        .parent()
        .map(Path::to_path_buf)
        .unwrap_or_else(|| PathBuf::from("."));
    let env_port = std::env::var("SUMMRISE_PORT").ok();
    let config = parse_config(args, &default_install, env_port.as_deref())?;
    Ok(Config {
        install: absolute(&config.install),
        data: absolute(&config.data),
        port: config.port,
    })
}

fn absolute(path: &Path) -> PathBuf {
    std::path::absolute(path).unwrap_or_else(|_| path.to_path_buf())
}

/// Parse `--install-service`'s arguments: the installer's normal flags, `--seed-sidecar <path>`, and
/// the remote link flags (console and mesh).
///
/// The seed sidecar is not a launcher flag — `parse_config` would refuse it, and a supervisor must
/// never accept a sidecar from argv, so it is removed here and passed to the installer only (NEW-1).
/// The remote flags are removed for the same reason and persisted as `<data>/console.json` (C3):
/// the service's argv carries no remote fact, and its environment is not settable from here.
fn parse_install_args(
    args: &[String],
) -> Result<(Config, Option<PathBuf>, Option<ConsoleLink>, bool), String> {
    let mut launcher_args = Vec::with_capacity(args.len());
    let mut seed_sidecar = None;
    let mut replace = false;
    let mut index = 0;
    while index < args.len() {
        if args[index] == "--replace-baseline" {
            replace = true;
            index += 1;
        } else if args[index] == "--seed-sidecar" {
            let value = args
                .get(index + 1)
                .ok_or_else(|| "--seed-sidecar needs a path".to_string())?;
            seed_sidecar = Some(absolute(Path::new(value)));
            index += 2;
        } else {
            launcher_args.push(args[index].clone());
            index += 1;
        }
    }
    let (launcher_args, console) = split_console_args(&launcher_args)?;
    let config = config_from_args(&launcher_args)?;
    Ok((config, seed_sidecar, console, replace))
}

/// Parse a `run` argv: the supervisor's flags plus the remote link, which is persisted not
/// forwarded (the child reads `<data>/console.json`).
fn config_with_console(args: &[String]) -> Result<(Config, Option<ConsoleLink>), String> {
    let (launcher_args, console) = split_console_args(args)?;
    Ok((config_from_args(&launcher_args)?, console))
}

/// Persist the remote link when the operator supplied one; leave an existing link alone otherwise.
///
/// An install without the flags does not erase a link a previous install wrote: the operator's only
/// instruction to disarm is to remove the file, and an idempotent `--install-service` must not turn
/// a working console or mesh channel off by being re-run.
fn persist_console_link(config: &Config, console: Option<&ConsoleLink>) -> Result<(), String> {
    match console {
        Some(link) => {
            // The app resolves the token path from its own working directory (the install root),
            // not the operator's shell; persisting an absolute path is the only stable spelling.
            // `link_to_persist` also carries a previously installed `mesh_stun` forward when this
            // rewrite names the mesh without naming a reflector.
            let link = link_to_persist(&config.data, link)?;
            write_console_link(&config.data, &link)?;
            Ok(())
        }
        None => Ok(()),
    }
}

/// The supervisor's single-instance guard (NEW-2).
///
/// Two supervisors for one install would both poll `swap.request.json` and both run the swap
/// transaction, racing `pending`, `current` and `previous`. The request file cannot arbitrate that:
/// both processes can consume it. A named mutex can, because the name is the install and Windows
/// ownership is exclusive. `Global\` (not `Local\`) is deliberate: the service runs in session 0 and
/// an operator's console supervisor in another session, and those must exclude each other too.
///
/// The name carries a digest of the normalized install path, so two different installs never block
/// each other. A mutex is released by the kernel when the last handle closes, including on a crash,
/// so a killed supervisor cannot leave a lock behind.
struct SupervisorLock(HANDLE);

impl SupervisorLock {
    fn acquire(install: &Path) -> Result<SupervisorLock, String> {
        let canonical = fs::canonicalize(install).unwrap_or_else(|_| install.to_path_buf());
        // Windows paths are case-insensitive; the hash must be too, or `D:\Summrise` and
        // `d:\summrise` would be two mutexes for one install.
        let normalized = canonical
            .to_string_lossy()
            .replace('/', "\\")
            .to_ascii_lowercase();
        let name = format!(
            "Global\\SummriseLaunch.Supervisor.{}",
            &sha256_bytes(normalized.as_bytes())[..32]
        );
        let wide: Vec<u16> = std::ffi::OsStr::new(&name)
            .encode_wide()
            .chain(std::iter::once(0))
            .collect();

        let handle = unsafe { CreateMutexW(std::ptr::null(), 0, wide.as_ptr()) };
        if handle == 0 {
            return Err(format!(
                "cannot create the single-instance mutex {name} ({}); refusing to supervise without it",
                io::Error::last_os_error()
            ));
        }
        // `CreateMutexW` opens an existing mutex as well as creating a new one; the error code is
        // the only way to tell the two apart.
        if unsafe { GetLastError() } == ERROR_ALREADY_EXISTS {
            unsafe { CloseHandle(handle) };
            return Err(format!(
                "another supervisor already owns {name} for this install ({}). One supervisor per \
                 install is allowed: stop the console `run` or the {SERVICE_NAME} service before \
                 starting another.",
                install.display()
            ));
        }
        Ok(SupervisorLock(handle))
    }
}

impl Drop for SupervisorLock {
    fn drop(&mut self) {
        unsafe { CloseHandle(self.0) };
    }
}

/// The console supervisor: `summrise-launch run`.
pub fn run_console(config: &Config) -> ExitCode {
    // The lock is taken before the pid file so a rejected second supervisor cannot overwrite the
    // running one's liveness record.
    let _lock = match SupervisorLock::acquire(&config.install) {
        Ok(lock) => lock,
        Err(error) => return exit_for(Err(error)),
    };
    if let Err(error) = fs::create_dir_all(&config.data) {
        eprintln!(
            "launch: cannot create the data directory {}: {error}",
            config.data.display()
        );
        return ExitCode::from(1);
    }
    let pid_file = launcher_pid_file(&config.data);
    let _ = fs::write(&pid_file, std::process::id().to_string());
    let stop = AtomicBool::new(false);
    let code = supervise(config, &stop);
    let _ = fs::remove_file(&pid_file);
    ExitCode::from(code.min(u8::MAX as u32) as u8)
}

/// The service entry: hand control to the SCM dispatcher, which calls [`service_main`] on its own
/// thread when the process really was started by the SCM. A console invocation fails fast here.
///
/// `name` is the SCM's name for this service, taken from `--service-name` when a registration other
/// than our installer's created it (see [`summrise_launch::parse_service_args`]).
pub fn run_service_entry(name: &str) -> ExitCode {
    match windows_service::service_dispatcher::start(name, ffi_service_main) {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!(
                "launch: the SCM did not start this process ({error}); run `summrise-launch run` for a console session"
            );
            ExitCode::from(1)
        }
    }
}

fn service_main(_arguments: Vec<OsString>) {
    let (name, launcher_args) = match service_arguments() {
        Ok(parts) => parts,
        Err(error) => {
            // Without a valid name there is no dispatcher table entry to report through.
            eprintln!("launch: cannot read the service arguments: {error}");
            return;
        }
    };
    let stop = Arc::new(AtomicBool::new(false));
    let signal = Arc::clone(&stop);
    let handler = move |control| -> ServiceControlHandlerResult {
        match control {
            ServiceControl::Stop | ServiceControl::Shutdown => {
                signal.store(true, Ordering::SeqCst);
                ServiceControlHandlerResult::NoError
            }
            ServiceControl::Interrogate => ServiceControlHandlerResult::NoError,
            _ => ServiceControlHandlerResult::NotImplemented,
        }
    };
    let status_handle = match service_control_handler::register(&name, handler) {
        Ok(handle) => handle,
        Err(error) => {
            eprintln!("launch: cannot register the service control handler for {name}: {error}");
            return;
        }
    };
    let config = match config_from_args(&launcher_args) {
        Ok(config) => config,
        Err(error) => {
            eprintln!("launch: cannot read the service arguments: {error}");
            report(
                &status_handle,
                ServiceState::Stopped,
                ServiceExitCode::ServiceSpecific(2),
            );
            return;
        }
    };
    // NEW-2: the same per-install lock the console takes. A service started beside a console
    // supervisor (or a second SCM instance) stops here instead of racing the swap transaction.
    let _lock = match SupervisorLock::acquire(&config.install) {
        Ok(lock) => lock,
        Err(error) => {
            eprintln!("launch: {error}");
            report(
                &status_handle,
                ServiceState::Stopped,
                ServiceExitCode::ServiceSpecific(1),
            );
            return;
        }
    };
    report(
        &status_handle,
        ServiceState::Running,
        ServiceExitCode::NO_ERROR,
    );

    let code = supervise(&config, &stop);
    // A CLEAN STOP MUST NOT LOOK LIKE A FAILURE. `ServiceSpecific(0)` sets the service's Win32 exit
    // code to 1066 (ERROR_SERVICE_SPECIFIC_ERROR), which the SCM counts as an error and answers with
    // the configured failure actions — the service an operator just stopped starts again by itself.
    // Only a real failure keeps the service-specific code; a zero exit is a plain `Win32(0)`.
    let exit = if code == 0 {
        ServiceExitCode::Win32(0)
    } else {
        ServiceExitCode::ServiceSpecific(code)
    };
    report(&status_handle, ServiceState::Stopped, exit);
}

/// The service's own arguments: the SCM name `--service-name` selected, and the flags
/// [`config_from_args`] accepts. The SCM starts the image with the binPath arguments, so argv[1] is
/// still `service`.
fn service_arguments() -> Result<(String, Vec<String>), String> {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let rest: &[String] = if args.first().map(String::as_str) == Some("service") {
        &args[1..]
    } else {
        &args[..]
    };
    parse_service_args(rest, SERVICE_NAME)
}

fn report(handle: &ServiceStatusHandle, state: ServiceState, exit_code: ServiceExitCode) {
    let controls = if state == ServiceState::Running {
        ServiceControlAccept::STOP | ServiceControlAccept::SHUTDOWN
    } else {
        ServiceControlAccept::empty()
    };
    let status = ServiceStatus {
        service_type: ServiceType::OWN_PROCESS,
        current_state: state,
        controls_accepted: controls,
        exit_code,
        checkpoint: 0,
        wait_hint: Duration::from_secs(0),
        process_id: None,
    };
    if let Err(error) = handle.set_service_status(status) {
        eprintln!("launch: cannot report the service status: {error}");
    }
}

/// The kill-on-close job that owns the supervised app children.
///
/// The job contains **only** app children. The supervisor performs a swap itself and never exits
/// while one is in flight (fix design F1), so there is no updater inside the job that a stop could
/// kill; `--apply` is an operator process started outside it. Closing this handle (which process
/// exit does implicitly) makes Windows terminate every app child, so a dead supervisor cannot leave
/// `summrise-device.exe` behind to race the next start for the port. The handle lives for the
/// supervisor's whole lifetime and is deliberately not closed by hand.
struct ChildJob(HANDLE);

impl ChildJob {
    fn create() -> Option<ChildJob> {
        use windows_sys::Win32::System::JobObjects::{
            CreateJobObjectW, JobObjectExtendedLimitInformation, SetInformationJobObject,
            JOBOBJECT_EXTENDED_LIMIT_INFORMATION, JOB_OBJECT_LIMIT_KILL_ON_JOB_CLOSE,
        };

        unsafe {
            let handle = CreateJobObjectW(std::ptr::null(), std::ptr::null());
            if handle == 0 {
                eprintln!(
                    "launch: warning: CreateJobObject failed ({}); a killed supervisor could orphan the app",
                    io::Error::last_os_error()
                );
                return None;
            }
            let mut info: JOBOBJECT_EXTENDED_LIMIT_INFORMATION = std::mem::zeroed();
            info.BasicLimitInformation.LimitFlags = JOB_OBJECT_LIMIT_KILL_ON_JOB_CLOSE;
            if SetInformationJobObject(
                handle,
                JobObjectExtendedLimitInformation,
                &info as *const _ as *const core::ffi::c_void,
                std::mem::size_of::<JOBOBJECT_EXTENDED_LIMIT_INFORMATION>() as u32,
            ) == 0
            {
                eprintln!(
                    "launch: warning: SetInformationJobObject failed ({}); a killed supervisor could orphan the app",
                    io::Error::last_os_error()
                );
                CloseHandle(handle);
                return None;
            }
            Some(ChildJob(handle))
        }
    }

    fn assign(&self, child: &Child) -> io::Result<()> {
        use std::os::windows::io::AsRawHandle;
        use windows_sys::Win32::System::JobObjects::AssignProcessToJobObject;

        let assigned = unsafe { AssignProcessToJobObject(self.0, child.as_raw_handle() as HANDLE) };
        if assigned == 0 {
            Err(io::Error::last_os_error())
        } else {
            Ok(())
        }
    }
}

impl Drop for ChildJob {
    fn drop(&mut self) {
        unsafe { CloseHandle(self.0) };
    }
}

