//! The React page's visual contract, checked by Rust.
//!
//! `device/console/web/src/tokens.css` is GENERATED from `device/ui::TOKENS`; the first test below
//! is the drift gate. The rest measure the values the page draws — the seven type sizes, one spacing
//! rhythm, the radii, the dark surfaces and every text pair the React page actually renders. A token
//! changed to a pretty value fails here, not in a screenshot someone forgets to open.

const TOKENS: &str = include_str!("../web/src/tokens.css");
const APP: &str = include_str!("../web/src/app.css");
const GENERATED_HEADER: &str =
    "/* Generated by scripts/generate-tokens.sh from device/ui/src/lib.rs. Do not edit. */\n";

/// The value of `--name:` anywhere in the sheet. The canonical sheet packs several declarations on
/// one line, so a line-based parser would return the rest of the line for the first one.
fn declared<'a>(css: &'a str, name: &str) -> Option<&'a str> {
    let needle = format!("--{name}:");
    let start = css.find(&needle)? + needle.len();
    let rest = &css[start..];
    let end = rest.find(';').unwrap_or(rest.len());
    Some(rest[..end].trim())
}

/// The literal behind an alias (`--surface:var(--panel)` follows to `--panel`). One hop is enough:
/// the sheet's aliases point at real values, not at each other.
fn follows<'a>(sheet: &'a str, name: &str) -> Option<&'a str> {
    // The dark block restates surfaces, not aliases: an alias declared once in :root still has to be
    // followed, and its target is the one the requested theme restates.
    let raw = declared(sheet, name).or_else(|| declared(TOKENS, name))?;
    match raw
        .strip_prefix("var(--")
        .and_then(|inner| inner.strip_suffix(')'))
    {
        Some(inner) => declared(sheet, inner).or_else(|| declared(TOKENS, inner)),
        None => Some(raw),
    }
}

fn all_declared<'a>(css: &'a str, prefix: &str) -> Vec<&'a str> {
    let mut out = Vec::new();
    let mut rest = css;
    while let Some(index) = rest.find(prefix) {
        let after = &rest[index..];
        let Some(colon) = after.find(':') else { break };
        let end = after.find(';').unwrap_or(after.len());
        out.push(after[colon + 1..end].trim());
        rest = &after[end..];
    }
    out
}

fn block(css: &str, start: usize) -> &str {
    &css[start..]
}

fn theme(dark: bool) -> &'static str {
    if dark {
        TOKENS
            .find("@media")
            .map(|index| block(TOKENS, index))
            .expect("the token sheet has a dark block")
    } else {
        TOKENS
    }
}

#[test]
fn generated_tokens_match_the_canonical_sheet() {
    let body = TOKENS
        .strip_prefix(GENERATED_HEADER)
        .expect("tokens.css carries the generated header");
    assert_eq!(
        body,
        summrise_ui::TOKENS,
        "the React sheet is stale; run scripts/generate-tokens.sh"
    );
}

#[test]
fn seven_type_sizes_and_a_thirteen_pixel_body() {
    let sizes = all_declared(TOKENS, "--fs-");
    assert_eq!(
        sizes,
        ["10px", "11px", "12px", "13px", "14px", "17px", "22px"],
        "the page has one seven-step type scale"
    );
    assert_eq!(declared(TOKENS, "fs-base"), Some("13px"));
}

#[test]
fn one_spacing_rhythm_and_the_canonical_radii() {
    let spacing: Vec<&str> = [
        "sp-0-5", "sp-1", "sp-1-5", "sp-2", "sp-2-5", "sp-3", "sp-3-5", "sp-4", "sp-5",
    ]
    .into_iter()
    .map(|name| declared(TOKENS, name).unwrap_or_else(|| panic!("--{name} is missing")))
    .collect();
    assert_eq!(
        spacing,
        ["2px", "4px", "6px", "8px", "10px", "12px", "14px", "16px", "24px"]
    );

    let radii: Vec<&str> = [
        "radius-xs",
        "radius-sm2",
        "radius-sm",
        "radius",
        "radius-lg",
    ]
    .into_iter()
    .map(|name| declared(TOKENS, name).unwrap_or_else(|| panic!("--{name} is missing")))
    .collect();
    assert_eq!(radii, ["6px", "8px", "10px", "14px", "20px"]);
    assert_eq!(declared(TOKENS, "accent"), Some("#bf3a0a"));
    assert_eq!(declared(TOKENS, "accent-solid"), Some("#b03a0a"));
    assert_eq!(declared(TOKENS, "radius-pill"), Some("999px"));
}

#[test]
fn the_dark_surfaces_are_restated_not_inherited() {
    let dark = theme(true);
    assert_eq!(declared(dark, "bg"), Some("#131418"));
    assert_eq!(declared(dark, "panel"), Some("#1c1d22"));
    assert_eq!(declared(dark, "ink"), Some("#ecedef"));
    assert_eq!(declared(dark, "accent"), Some("#ffa36b"));
    assert_eq!(declared(dark, "term-canvas"), Some("#0f1014"));
    // The aliases are not restated; they resolve through the panel tokens that are.
    assert_eq!(declared(dark, "surface"), None);
    assert_eq!(follows(dark, "surface"), Some("#1c1d22"));
}

// ── THE REACT PAGE'S OWN COLOUR PAIRS ─────────────────────────────────────────────────────────────
//
// The maud fallback has its own measured AA test in `src/http/page.rs`; the React page's sheet had
// none, so `--ink-faint` shipped as #a1a1aa — 2.46:1 on white, used at 11px — and nothing failed.
// This test reads the SAME sheet Vite builds, resolves the two themes, and measures every
// text-on-surface pair the page actually draws.

/// A `#rrggbb` token as channels in 0..=1. Alpha tokens are not admitted: a pair measured against a
/// colour it is not composited on is a number, not a verdict.
fn rgb(hex: &str) -> (f64, f64, f64) {
    let body = hex
        .strip_prefix('#')
        .unwrap_or_else(|| panic!("{hex} is not a #rrggbb token"));
    assert_eq!(body.len(), 6, "{hex} is not a #rrggbb token");
    let channel = |index: usize| {
        u8::from_str_radix(&body[index..index + 2], 16).expect("a hex channel") as f64 / 255.0
    };
    (channel(0), channel(2), channel(4))
}

fn luminance(value: (f64, f64, f64)) -> f64 {
    let linear = |channel: f64| {
        if channel <= 0.040_45 {
            channel / 12.92
        } else {
            ((channel + 0.055) / 1.055).powf(2.4)
        }
    };
    0.2126 * linear(value.0) + 0.7152 * linear(value.1) + 0.0722 * linear(value.2)
}

fn contrast(ink: &str, surface: &str) -> f64 {
    let a = luminance(rgb(ink));
    let b = luminance(rgb(surface));
    let (light, dark) = if a >= b { (a, b) } else { (b, a) };
    (light + 0.05) / (dark + 0.05)
}

#[test]
fn every_text_pair_reads_on_the_surface_it_sits_on() {
    // (ink, surface): the pairs a reader actually sees, named by the use rather than the page.
    let pairs: &[(&str, &str, &str)] = &[
        ("body on a card", "ink", "surface"),
        ("body on the page", "ink", "bg"),
        ("hint on a card", "ink-muted", "surface"),
        ("hint on the page", "ink-muted", "bg"),
        ("faint label on a card", "ink-faint", "surface"),
        ("faint label on the page", "ink-faint", "bg"),
        ("faint label on a chip", "ink-faint", "surface-chip"),
        ("primary button label", "accent-fg", "accent-solid"),
        ("success on its wash", "ok", "ok-soft"),
        ("warning on its wash", "warn", "warn-soft"),
        ("error on its wash", "error", "error-soft"),
    ];
    for dark in [false, true] {
        let sheet = theme(dark);
        for (use_name, ink, surface) in pairs {
            // The dark success wash is a translucent green; it is measured by the runtime probe, not
            // compared against a hex it is not the background of.
            if dark && (*ink == "ok") {
                continue;
            }
            let ink_value = follows(sheet, ink).unwrap_or_else(|| panic!("--{ink} is missing"));
            let surface_value =
                follows(sheet, surface).unwrap_or_else(|| panic!("--{surface} is missing"));
            let measured = contrast(ink_value, surface_value);
            assert!(
                measured >= 4.5,
                "{use_name}: --{ink} {ink_value} on --{surface} {surface_value} measures {measured:.2}:1 in {} (AA needs 4.5)",
                if dark { "dark" } else { "light" }
            );
        }
    }
}

#[test]
fn every_weight_is_one_of_four_tokens() {
    // The sheet had 26 literal weights across five values (450/500/550/600/650). The family is now
    // four documented steps; a new literal, or a renamed token, fails here instead of drifting.
    for (name, expected) in [
        ("fw-regular", "400"),
        ("fw-medium", "500"),
        ("fw-semi", "600"),
        ("fw-bold", "700"),
    ] {
        assert_eq!(declared(TOKENS, name), Some(expected), "--{name}");
    }
    for line in APP.lines() {
        let Some(index) = line.find("font-weight:") else {
            continue;
        };
        let weight = line[index + "font-weight:".len()..]
            .split(';')
            .next()
            .unwrap_or("")
            .trim();
        assert!(
            weight.starts_with("var(--fw-"),
            "literal font weight: {line}"
        );
    }
}

#[test]
fn every_type_size_comes_from_the_seven_step_scale() {
    // Two declarations had escaped the scale (0.95rem for a close glyph, 0.65rem for a status pill).
    // A raw length here means a new size nobody measured against the body's 13px.
    for line in APP.lines() {
        let Some(index) = line.find("font-size:") else {
            continue;
        };
        let size = line[index + "font-size:".len()..]
            .split(';')
            .next()
            .unwrap_or("")
            .trim();
        assert!(
            size.starts_with("var(--fs-"),
            "font size outside the scale: {line}"
        );
    }
}

/// Does `value` contain `literal` as a whole length, not as the tail of `0.1rem` or `1.15rem`?
fn contains_length(value: &str, literal: &str) -> bool {
    let mut from = 0;
    while let Some(index) = value[from..].find(literal) {
        let start = from + index;
        let before = value[..start].chars().last();
        let after = value[start + literal.len()..].chars().next();
        let boundary = |c: Option<char>| !matches!(c, Some(c) if c.is_ascii_digit() || c == '.');
        if boundary(before) && boundary(after) {
            return true;
        }
        from = start + 1;
    }
    false
}

#[test]
fn spacing_uses_the_rhythm_when_the_value_is_already_on_it() {
    // 104 declarations were written in rem values that already WERE a rhythm step (0.25rem = 4px,
    // 0.5rem = 8px, ...). Moving them onto --sp-* is pixel-identical; this gate stops the next
    // 0.5rem from being typed by hand. The off-scale values (0.35rem, 0.65rem, ...) are the next
    // batch and are deliberately not asserted away here.
    let properties = [
        "padding",
        "margin",
        "gap",
        "row-gap",
        "column-gap",
        "top",
        "right",
        "bottom",
        "left",
        "inset",
    ];
    let literals = [
        ("0.125rem", "0-5"),
        ("0.25rem", "1"),
        ("0.375rem", "1-5"),
        ("0.5rem", "2"),
        ("0.625rem", "2-5"),
        ("0.75rem", "3"),
        ("0.875rem", "3-5"),
        ("1rem", "4"),
        ("1.5rem", "5"),
    ];
    for line in APP.lines() {
        if !properties.iter().any(|property| line.contains(property)) {
            continue;
        }
        assert!(
            !line.contains(".var(--sp-"),
            "a spacing token was spliced into a decimal: {line}"
        );
        for (literal, step) in literals {
            assert!(
                !contains_length(line, literal),
                "spacing literal {literal} is --sp-{step}; write the token: {line}"
            );
        }
    }
}

#[test]
fn spacing_is_the_rhythm_or_a_documented_exception() {
    // Six lengths are not on the nine-step rhythm, and each is a structural measurement rather than
    // a spacing choice: the 0.05/0.1rem control hairlines, the 1.1/1.2rem sheet padding, the 2rem
    // boot/login padding and the 2.6rem offset above the status bar. Everything else must be a
    // --sp-* token; a new 0.35rem is a new decision, and it has to be made here.
    let allowed = ["0.05rem", "0.1rem", "1.1rem", "1.2rem", "2rem", "2.6rem"];
    let properties = [
        "padding",
        "margin",
        "gap",
        "row-gap",
        "column-gap",
        "top",
        "right",
        "bottom",
        "left",
        "inset",
    ];
    for line in APP.lines() {
        // A line can carry a width and a padding (`max-width:84rem; padding:...`); the width is not
        // a spacing decision, so only the value of a spacing PROPERTY is inspected.
        for declaration in line.split(';') {
            let Some((name, value)) = declaration.split_once(':') else {
                continue;
            };
            let name = name.trim();
            if !properties
                .iter()
                .any(|property| name == *property || name.starts_with(&format!("{property}-")))
            {
                continue;
            }
            for word in value.split_whitespace() {
                let Some(number) = word.strip_suffix("rem") else {
                    continue;
                };
                let value = format!("{number}rem");
                assert!(
                    allowed.contains(&value.as_str()),
                    "spacing length {value} is neither a --sp-* token nor a documented exception: {line}"
                );
            }
        }
    }
}
