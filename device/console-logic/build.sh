#!/usr/bin/env bash
# Build console-logic to wasm and install it where the console page imports it.
#
#   ./build.sh          build, optimize, copy the glue and the bytes, refresh the freshness stamp
#
# WHY THE WASM IS INLINED AS BASE64. The console page is ONE committed HTML file embedded in the
# console binary; there is no asset directory to fetch a .wasm from. The page instantiates the module
# from the bytes at startup, so the binary still carries one artifact and no route was added.
#
# WHY wasm-opt IS MANDATORY. An unoptimized module is 33 KB / 17 KB gz against 20.8 KB / 9.6 KB
# optimized. The bytes are committed, so nothing downstream re-derives them; a build that cannot
# optimize must fail rather than silently commit the larger artifact.
set -euo pipefail
cd "$(dirname "$0")"
export PATH="$HOME/.cargo/bin:$PATH"

WASM_OPT="${WASM_OPT:-$(command -v wasm-opt || true)}"
if [ -z "$WASM_OPT" ] && [ -x /home/zss/wasmopt/node_modules/.bin/wasm-opt ]; then
  WASM_OPT=/home/zss/wasmopt/node_modules/.bin/wasm-opt
fi
if [ -z "$WASM_OPT" ]; then
  echo "build.sh: no wasm-opt; install binaryen (npm i -g binaryen) or set WASM_OPT" >&2
  exit 1
fi

echo "── wasm-pack build --target web --no-opt ──"
wasm-pack build --target web --no-opt

echo "── wasm-opt -Oz ($("$WASM_OPT" --version 2>/dev/null | head -1)) ──"
"$WASM_OPT" -Oz --enable-bulk-memory --enable-nontrapping-float-to-int \
  pkg/console_logic_bg.wasm -o pkg/console_logic_bg.wasm.opt
mv pkg/console_logic_bg.wasm.opt pkg/console_logic_bg.wasm

DEST=../console/web/src/wasm
mkdir -p "$DEST"
cp pkg/console_logic.js "$DEST/console_logic.js"
cp pkg/console_logic.d.ts "$DEST/console_logic.d.ts"
cp pkg/console_logic_bg.wasm "$DEST/console_logic_bg.wasm"

# THE GLUE MUST NOT RESOLVE A URL TO A FILE THAT DOES NOT EXIST. The default branch would make Vite
# emit a separate .wasm asset (which the single-file page cannot serve) even though the page always
# passes bytes to init(). Replace it with the sentence a caller who forgot the bytes should read.
python3 - "$DEST/console_logic.js" <<'PY'
import sys
p = sys.argv[1]
s = open(p).read()
old = "        module_or_path = new URL('console_logic_bg.wasm', import.meta.url);"
new = "        throw new Error('console-logic: pass the wasm bytes to init()');"
if old not in s:
    raise SystemExit('build.sh: the glue changed; the URL branch was not found')
open(p, 'w').write(s.replace(old, new, 1))
PY

BASE64=$(base64 -w0 "$DEST/console_logic_bg.wasm")
cat > "$DEST/console_logic_bg.ts" <<TS
// GENERATED by device/console-logic/build.sh. Do not edit: the bytes and this text are one artifact.
// The page imports this string, decodes it once and hands the bytes to the wasm-bindgen init().
export const CONSOLE_LOGIC_WASM_BASE64 =
  '$BASE64';
TS

# The stamp is the source half of the freshness proof: a source edit with no rebuild is a stale
# artifact, and it is the only thing a checkout can check without a Rust toolchain.
sha256sum Cargo.toml src/lib.rs | sha256sum | cut -d' ' -f1 > LOGIC_SOURCE.sha256

printf 'wasm   : %6s bytes / %6s gzipped\n' \
  "$(stat -c%s "$DEST/console_logic_bg.wasm")" "$(gzip -9 -c "$DEST/console_logic_bg.wasm" | wc -c)"
printf 'base64 : %6s bytes\n' "$(stat -c%s "$DEST/console_logic_bg.ts")"
printf 'stamp  : %s\n' "$(cat LOGIC_SOURCE.sha256)"
