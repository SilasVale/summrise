use serde_json::{Map, Value};

/// `resolveHost(headers)` — the REAL public host, with `x-forwarded-host` first.
///
/// nginx fronts the relay (`location /api/ -> 127.0.0.1:8081`, Host preserved), so a request's own
/// origin is `https://<public host>`; gform's body rewriting builds proxy URLs from that origin and must
/// see the real host rather than the loopback one.
pub fn resolve_host(headers: &Map<String, Value>) -> Value {
    // `headers["x-forwarded-host"] || headers.host || "localhost"` — TRUTHINESS at each step, so an
    // EMPTY x-forwarded-host falls through to `host` and an empty host falls through to the default.
    for key in ["x-forwarded-host", "host"] {
        if let Some(v) = headers.get(key) {
            // TRUTHINESS, not "is the text non-empty": `null` is FALSY, so
            // `{"x-forwarded-host": null, host: "api.saisi.online"}` answers the host — and the first
            // version of this port returned the string `"null"`, which the fixture caught. An empty
            // ARRAY is truthy and stringifies to `""`, which is the other half of the same rule.
            if truthy(v) {
                // THE RAW VALUE, NOT ITS TEXT: `headers["x-forwarded-host"] || headers.host` returns
                // whatever it found, so a NUMBER or an ARRAY is the answer — and `JSON.stringify` of it
                // is what the fixture carries. The coercion happens where the host is USED, in
                // `build_url`'s template, which is exactly where the JavaScript does it.
                return v.clone();
            }
        }
    }
    Value::String("localhost".to_string())
}

/// JavaScript TRUTHINESS for a JSON value — `false` for `null`, `false`, `0`, `NaN` and `""`, and
/// `true` for every array and object (an EMPTY one included).
fn truthy(v: &Value) -> bool {
    match v {
        Value::Null => false,
        Value::Bool(b) => *b,
        Value::Number(n) => n.as_f64().is_some_and(|f| f != 0.0 && !f.is_nan()),
        Value::String(s) => !s.is_empty(),
        Value::Array(_) | Value::Object(_) => true,
    }
}

/// `${v}` — the template coercion. A header value is normally a string; an ARRAY reaches here because
/// Node's `rawHeaders`-shaped objects carry multi-values as arrays, and `String([a, b])` is `"a,b"`.
fn js_text(v: &Value) -> String {
    match v {
        Value::Null => "null".to_string(),
        Value::Bool(b) => b.to_string(),
        Value::Number(n) => n.to_string(),
        Value::String(s) => s.clone(),
        Value::Array(items) => items
            .iter()
            .map(|i| match i {
                Value::Null => String::new(),
                other => js_text(other),
            })
            .collect::<Vec<_>>()
            .join(","),
        Value::Object(_) => "[object Object]".to_string(),
    }
}

/// One entry of the routes table: `{ prefix, handler, pathFromRest? }`. `handler` stays an OPAQUE
/// value — `resolveRoute` never calls it, and in the JavaScript the real functions exist only in
/// `dist/`, which is why the test file passes a synthetic table.
#[derive(Debug, Clone, PartialEq)]
pub struct Route {
    pub prefix: String,
    pub handler: Value,
    pub path_from_rest: bool,
}

/// A route hit: the route, the pathname and the search string (WITHOUT its `?`).
#[derive(Debug, Clone, PartialEq)]
pub struct Hit {
    pub route: Route,
    pub pathname: String,
    pub search: String,
}

/// `resolveRoute(routes, rawUrl)` — the FIRST route whose prefix matches, or nothing.
///
/// THE SEPARATOR IS THE WHOLE POINT: `pathname === r.prefix || pathname.startsWith(r.prefix + "/")`,
/// so `/api/gitx` matches NOTHING and `/api/git/…` does not become `/api/github/…` by a prefix test.
pub fn resolve_route(routes: &[Route], raw_url: &str) -> Option<Hit> {
    let qmark = raw_url.find('?');
    let (pathname, search) = match qmark {
        Some(i) => (&raw_url[..i], &raw_url[i + 1..]),
        None => (raw_url, ""),
    };
    for r in routes {
        if pathname == r.prefix || pathname.starts_with(&format!("{}/", r.prefix)) {
            return Some(Hit {
                route: r.clone(),
                pathname: pathname.to_string(),
                search: search.to_string(),
            });
        }
    }
    None
}

/// `buildUrl({ r, pathname, search }, host)` — the upstream Request URL for a route hit.
///
/// A `pathFromRest` route FOLDS THE TAIL INTO A `path` QUERY PARAM, which is the shape the deleted
/// `vercel.json` declared as `"/api/git/:path*" -> "/api/git?path=/:path*"`. The original query args are
/// preserved — git's smart-http needs `service=git-upload-pack` — and a caller-supplied `path=` is
/// DROPPED, because it would collide with the rewritten one.
pub fn build_url(hit: &Hit, host: &Value) -> String {
    let host = js_text(host);
    let host = host.as_str();
    let r = &hit.route;
    if !r.path_from_rest {
        return format!(
            "https://{host}{}{}",
            hit.pathname,
            if hit.search.is_empty() {
                String::new()
            } else {
                format!("?{}", hit.search)
            }
        );
    }
    let rest = &hit.pathname[r.prefix.len()..];
    // `"/" + rest.replace(/^\//, "")` — the leading slash is dropped and exactly one is put back.
    let path = format!("/{}", rest.strip_prefix('/').unwrap_or(rest));
    let mut params = FormParams::new();
    params.set("path", &path);
    if !hit.search.is_empty() {
        for (k, v) in FormParams::parse(&hit.search).entries() {
            if k != "path" {
                params.append(&k, &v);
            }
        }
    }
    format!("https://{host}{}?{params}", r.prefix)
}

/// `URLSearchParams` — the application/x-www-form-urlencoded codec, which is what `toString()` emits
/// and what the constructor parses.
///
/// IT IS A CODEC RATHER THAN A STRING JOIN, and the corpus is why: a space is `+` on the way out and
/// `+` is a space on the way in, `%2F` decodes to `/` and is re-encoded as `%2F`, and a `%` that is not
/// followed by two hex digits is left LITERAL (the spec's forgiving decode) rather than raising.
#[derive(Default)]
pub struct FormParams(Vec<(String, String)>);

impl FormParams {
    pub fn new() -> Self {
        FormParams(Vec::new())
    }

    /// `params.set(k, v)` — the spec's rule: the FIRST pair with that name takes the value and every
    /// LATER one is removed; if there is none, a pair is appended. (The first version of this walked
    /// the list with a `retain` that compared pointers, which is not a rule at all.)
    pub fn set(&mut self, k: &str, v: &str) {
        let mut found = false;
        let mut out: Vec<(String, String)> = Vec::new();
        for (name, value) in std::mem::take(&mut self.0) {
            if name == k {
                if !found {
                    out.push((name, v.to_string()));
                    found = true;
                }
            } else {
                out.push((name, value));
            }
        }
        if !found {
            out.push((k.to_string(), v.to_string()));
        }
        self.0 = out;
    }

    pub fn append(&mut self, k: &str, v: &str) {
        self.0.push((k.to_string(), v.to_string()));
    }

    /// `params.delete(k)` — every pair with that name goes.
    pub fn remove(&mut self, k: &str) {
        self.0.retain(|(name, _)| name != k);
    }

    pub fn entries(&self) -> Vec<(String, String)> {
        self.0.clone()
    }

    /// `new URLSearchParams(search)` — split on `&`, then on the FIRST `=`, then decode both halves.
    /// An empty input has NO entries (not one empty pair), which is what the spec says.
    pub fn parse(search: &str) -> Self {
        let mut out = FormParams::new();
        if search.is_empty() {
            return out;
        }
        for pair in search.split('&') {
            let (k, v) = match pair.find('=') {
                Some(i) => (&pair[..i], &pair[i + 1..]),
                None => (pair, ""),
            };
            out.0.push((form_decode(k), form_decode(v)));
        }
        out
    }
}

/// `URLSearchParams.prototype.toString()` — `k=v&k=v`, each half percent-encoded with the urlencoded
/// set. It is `Display` rather than an inherent `to_string`, which is what `clippy` asked for and what
/// the callers want anyway.
impl std::fmt::Display for FormParams {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        let joined = self
            .0
            .iter()
            .map(|(k, v)| format!("{}={}", form_encode(k), form_encode(v)))
            .collect::<Vec<_>>()
            .join("&");
        write!(f, "{joined}")
    }
}

/// The `application/x-www-form-urlencoded` DECODE: `+` is a space, `%XX` is a byte, and anything else
/// (including a `%` with no two hex digits after it) is literal. Bytes are then read as UTF-8, with
/// invalid sequences replaced — which is what the `USVString` conversion does.
pub fn form_decode(s: &str) -> String {
    let bytes = s.as_bytes();
    let mut out: Vec<u8> = Vec::new();
    let mut i = 0;
    while i < bytes.len() {
        match bytes[i] {
            b'+' => {
                out.push(b' ');
                i += 1;
            }
            b'%' if i + 2 < bytes.len() => {
                let hex = |c: u8| (c as char).to_digit(16);
                match (hex(bytes[i + 1]), hex(bytes[i + 2])) {
                    (Some(hi), Some(lo)) => {
                        out.push((hi * 16 + lo) as u8);
                        i += 3;
                    }
                    _ => {
                        out.push(b'%');
                        i += 1;
                    }
                }
            }
            b => {
                out.push(b);
                i += 1;
            }
        }
    }
    String::from_utf8_lossy(&out).to_string()
}

/// The urlencoded ENCODE: everything except `A-Za-z0-9*-._` is percent-encoded, and a space is `+`.
pub fn form_encode(s: &str) -> String {
    let mut out = String::new();
    for b in s.as_bytes() {
        match b {
            b' ' => out.push('+'),
            b'A'..=b'Z' | b'a'..=b'z' | b'0'..=b'9' | b'*' | b'-' | b'.' | b'_' => {
                out.push(*b as char)
            }
            other => out.push_str(&format!("%{other:02X}")),
        }
    }
    out
}

// ── THE HEADER PLUMBING (`forwardHeaders` · `collectResponseHeaders`) ─────────────────────────────
//
// These two decide what rides upstream and what rides back, and they are WHATWG `Headers` semantics
// rather than a dictionary: names are LOWERCASED and validated as HTTP tokens, values are trimmed of
// HTTP whitespace and validated, iteration is SORTED BY NAME, and multiple values COMBINE — with `; `
// for `cookie` (the spec's own special case, so a session cookie is not torn apart by a comma) and
// `, ` for everything else. `set-cookie` is NOT combined: it rides as one entry per value, which is
// exactly why `collect_response_headers` puts the array back.

/// The HTTP whitespace a header value is trimmed of: SP, HT, LF, CR.
fn trim_http_whitespace(s: &str) -> &str {
    s.trim_matches(|c| matches!(c, ' ' | '\t' | '\n' | '\r'))
}

/// An HTTP token (RFC 9110): `!#$%&'*+-.^_`|~` and the alphanumerics. A name outside this set is a
/// TypeError in the `Headers` API, and the corpus carries one.
fn is_token(s: &str) -> bool {
    !s.is_empty()
        && s.bytes().all(|b| {
            b.is_ascii_alphanumeric()
                || matches!(
                    b,
                    b'!' | b'#'
                        | b'$'
                        | b'%'
                        | b'&'
                        | b'\''
                        | b'*'
                        | b'+'
                        | b'-'
                        | b'.'
                        | b'^'
                        | b'_'
                        | b'`'
                        | b'|'
                        | b'~'
                )
        })
}

/// A header value may not carry NUL, LF or CR — `Headers` raises, and this is the check that says so
/// rather than writing a header that would split the request.
///
/// **AND IT MUST BE A BYTE STRING**: every code point at or below U+00FF. `new Headers().set("x", "中")`
/// is a TypeError ("Cannot convert argument to a ByteString… greater than 255"), which the corpus found
/// by carrying one — a port that accepted it would put a header on the wire that no `Headers` object
/// would ever have produced.
fn is_valid_value(s: &str) -> bool {
    !s.contains('\0')
        && !s.contains('\n')
        && !s.contains('\r')
        && s.chars().all(|c| (c as u32) <= 0xFF)
}

/// `forwardHeaders(rawHeaders)` — the inbound headers for the upstream Request.
///
/// Drops hop-by-hop noise (`host`, which is rebuilt from the upstream URL, and HTTP/2 pseudo-headers)
/// and returns the header LIST the way `[...headers.entries()]` reads it: lowercased names, sorted,
/// multi-values combined. The first version of this port returned a map and lost both the order and the
/// combining, which the corpus would have caught on its first set-cookie case.
pub fn forward_headers(raw: &Map<String, Value>) -> Result<Vec<(String, String)>, String> {
    let mut list: Vec<(String, String)> = Vec::new();
    for (k, v) in raw {
        if k == "host" || k.starts_with(':') {
            continue;
        }
        let values: Vec<Value> = match v {
            Value::Array(items) => items.clone(),
            other => vec![other.clone()],
        };
        let multi = matches!(v, Value::Array(_));
        for one in values {
            let name = k.to_lowercase();
            if !is_token(&name) {
                return Err(format!("invalid header name: {k:?}"));
            }
            let value = trim_http_whitespace(&js_text(&one)).to_string();
            if !is_valid_value(&value) {
                return Err(format!("invalid header value for {name:?}"));
            }
            if multi {
                list.push((name, value));
            } else {
                // `headers.set(k, v)` REPLACES every existing entry — and since an object cannot repeat
                // a key, that only differs from `append` when the name collides after LOWERCASING.
                list.retain(|(n, _)| n != &name);
                list.push((name, value));
            }
        }
    }
    Ok(combine(list))
}

/// The spec's sort-and-combine: sorted by name, one entry per name — except `set-cookie`, which rides
/// as one entry PER VALUE — with `cookie` joined by `; ` and everything else by `, `.
fn combine(list: Vec<(String, String)>) -> Vec<(String, String)> {
    let mut names: Vec<String> = Vec::new();
    for (n, _) in &list {
        if !names.contains(n) {
            names.push(n.clone());
        }
    }
    names.sort();
    let mut out = Vec::new();
    for name in names {
        let values: Vec<String> = list
            .iter()
            .filter(|(n, _)| n == &name)
            .map(|(_, v)| v.clone())
            .collect();
        if name == "set-cookie" {
            for v in values {
                out.push((name.clone(), v));
            }
        } else {
            let sep = if name == "cookie" { "; " } else { ", " };
            out.push((name, values.join(sep)));
        }
    }
    out
}

/// `collectResponseHeaders(response)` — the plain-object headers for the `node:http` reply.
///
/// `entries` is the upstream's combined list and `set_cookie` its `getSetCookie()` values: multi
/// set-cookie values ride as an ARRAY, because gform's reCAPTCHA session needs ALL of them rather than
/// the first.
///
/// **`content-length` AND `content-encoding` ARE DROPPED ON PURPOSE, AND IT IS A CORRECTNESS FIX RATHER
/// THAN TIDINESS** (the JavaScript's own note, round 126): `fetch` TRANSPARENTLY DECOMPRESSES the body
/// and leaves both headers exactly as the upstream sent them, so forwarding them makes the reply a lie
/// — a length that is no longer the length and a `gzip` over bytes that are no longer compressed. It is
/// reachable rather than theoretical, because `forward_headers` passes the CALLER's `accept-encoding`
/// upstream.
pub fn collect_response_headers(entries: &[(String, String)], set_cookie: &[String]) -> Value {
    let mut out = Map::new();
    for (k, v) in entries {
        // `Object.fromEntries` keeps the LAST value for a repeated key, and a numeric-looking key would
        // jump to the front of a JavaScript object — header names are neither.
        out.insert(k.clone(), Value::String(v.clone()));
    }
    if !set_cookie.is_empty() {
        out.insert(
            "set-cookie".to_string(),
            Value::Array(
                set_cookie
                    .iter()
                    .map(|v| Value::String(v.clone()))
                    .collect(),
            ),
        );
    }
    out.remove("content-length");
    out.remove("content-encoding");
    Value::Object(out)
}

// ── `/api/proxy`'s DECISIONS: the CORS copy and the upstream request plan ─────────────────────────
//
// BYOK-ONLY, AND DEFAULT-CLOSED. The caller MUST supply their own OpenRouter key in `Authorization`;
// there is no built-in env key to spend, so a request without one is refused with 401 rather than
// relayed. And any Origin outside the allowlist gets NO `Access-Control-Allow-Origin` header at all —
// absence is the refusal, which is why the corpus pins `null` rather than a string.

/// The console origins this relay serves. The gateway's `http.ts` holds the same closed set, and
/// `proxy-gate.test.mjs` is the test that keeps the two copies equal.
const ALLOWED_ORIGINS: [&str; 2] = ["https://ai.saisi.online", "https://api.saisi.online"];

/// The headers `/api/proxy` will forward upstream. Anything else the caller sends is DROPPED — the
/// list is an allowlist, not a filter.
const SAFE: [&str; 6] = [
    "accept",
    "accept-encoding",
    "accept-language",
    "anthropic-version",
    "content-type",
    "user-agent",
];

/// `new URL(request.url).hostname`, with `""` for a URL that does not parse — the JavaScript's `catch`.
pub fn request_host(url: &str) -> String {
    url::Url::parse(url)
        .ok()
        .and_then(|u| u.host_str().map(|h| h.to_string()))
        .unwrap_or_default()
}

/// A loopback Origin is a LOCAL-DEV affordance, not a production grant: `http:`/`https:` on
/// `localhost` or `127.0.0.1`.
pub fn is_loopback_origin(origin: &str) -> bool {
    match url::Url::parse(origin) {
        Ok(u) => {
            matches!(u.scheme(), "http" | "https")
                && matches!(u.host_str(), Some("localhost") | Some("127.0.0.1"))
        }
        Err(_) => false,
    }
}

/// `corsHeaders(request)` — the object the handler spreads into every reply.
///
/// **THE LOOPBACK RULE IS THE TRAP THIS KEEPS CLOSED**: a loopback Origin is reflected only when the
/// REQUEST HOST is itself loopback, so the deployed relay never reflects a foreign page's
/// `http://localhost` Origin. The corpus carries that pair both ways.
pub fn cors_headers(origin: &str, request_host: &str) -> Vec<(String, String)> {
    let mut out = vec![
        (
            "Access-Control-Allow-Methods".to_string(),
            "GET,POST,OPTIONS".to_string(),
        ),
        ("Access-Control-Allow-Headers".to_string(), "*".to_string()),
    ];
    let loopback_host = matches!(request_host, "localhost" | "127.0.0.1");
    if ALLOWED_ORIGINS.contains(&origin) || (is_loopback_origin(origin) && loopback_host) {
        out.push((
            "Access-Control-Allow-Origin".to_string(),
            origin.to_string(),
        ));
        out.push(("Vary".to_string(), "Origin".to_string()));
    }
    out
}

/// What the handler decided to do with a request.
#[derive(Debug, Clone, PartialEq)]
pub enum ProxyPlan {
    /// `OPTIONS` SHORT-CIRCUITS BEFORE THE GATE: the reply is the CORS object and nothing else — no
    /// authorization check, no upstream call. The corpus found this by carrying an `OPTIONS` request
    /// WITH a caller key: the JavaScript answered 200 and never dialled, and the first version of this
    /// port planned an upstream request for it.
    Preflight,
    /// The 401 the caller gets, with the JSON body the JavaScript writes.
    Refused { status: u16, error: String },
    /// What rides upstream, in order, and whether a body goes with it.
    Send {
        headers: Vec<(String, String)>,
        send_body: bool,
    },
}

/// `handler`'s request half: which headers ride upstream, or the refusal.
///
/// THE ORDER OF THE THREE WRITES MATTERS AND IS THE JAVASCRIPT'S: the allowlist is copied first, then
/// `Authorization`, then `Content-Type` — which OVERRIDES a caller's own `content-type`, even though
/// `content-type` is in the allowlist — and finally the `anthropic-version` default, only if the
/// caller did not supply one.
pub fn proxy_upstream_plan(method: &str, headers: &Map<String, Value>) -> ProxyPlan {
    if method == "OPTIONS" {
        return ProxyPlan::Preflight;
    }
    let get = |name: &str| -> Option<String> {
        // `request.headers.get(n)` IS CASE-INSENSITIVE, and the harness passes the request's headers as
        // a plain object — so the lookup folds the name rather than trusting the caller's spelling.
        headers
            .iter()
            .find(|(k, _)| k.to_lowercase() == name)
            .map(|(_, v)| js_text(v))
    };
    let mut out: Vec<(String, String)> = Vec::new();
    for name in SAFE {
        // `if (v)` — TRUTHINESS, so an empty header is not forwarded as an empty header.
        if let Some(v) = get(name) {
            if !v.is_empty() {
                out.push((name.to_string(), v));
            }
        }
    }
    let Some(client_auth) = get("authorization").filter(|v| !v.is_empty()) else {
        return ProxyPlan::Refused {
            status: 401,
            error: "caller Authorization required (BYOK)".to_string(),
        };
    };
    // THE NAMES ARE LOWERCASED AND THE LIST IS SORTED, because that is what `Headers.set` and
    // `[...headers.entries()]` do — and the corpus reads the upstream request exactly that way. The
    // first version kept the caller's capitalisation and the insertion order, which is a different
    // observable value for the same request.
    out.push(("authorization".to_string(), client_auth));
    out.retain(|(k, _)| k != "content-type");
    out.push(("content-type".to_string(), "application/json".to_string()));
    if !out.iter().any(|(k, _)| k == "anthropic-version") {
        out.push(("anthropic-version".to_string(), "2023-06-01".to_string()));
    }
    ProxyPlan::Send {
        headers: combine(out),
        // GET/HEAD carry no body: passing one throws on some runtimes, so only methods with a body send
        // one — and `includes` is an EXACT, case-sensitive comparison.
        send_body: matches!(method, "POST" | "PUT" | "PATCH"),
    }
}

// ── THE `api/git` GATE'S TWO DECISIONS (`validPath` · `allowedRedirect`) ─────────────────────────
//
// THE SMART-HTTP RELAY'S SECURITY SURFACE, and both halves are STRICTER than the github handler's on
// purpose: the redirect allowlist here is `github.com` EXACTLY (no asset hosts, no `www`), and the path
// is checked BOTH as written and after PERCENT-DECODING — because `%2e%2e%2f` is a `..` that a
// written-form check never sees.

/// `decodeURIComponent(value)`: `%XX` is a byte, the bytes are read as UTF-8, and **ANY malformed input
/// is an ERROR** — a `%` with no two hex digits after it, or bytes that are not UTF-8.
///
/// IT IS NOT `form_decode`: `+` is a PLUS here rather than a space, and `form_decode` answers a lossy
/// replacement where this raises. The TypeScript's `try/catch` around `decodeURIComponent` is the
/// `Result` this returns.
fn decode_uri_component(s: &str) -> Result<String, ()> {
    let bytes = s.as_bytes();
    let mut out: Vec<u8> = Vec::new();
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == b'%' {
            if i + 2 >= bytes.len() {
                return Err(());
            }
            let hex = |c: u8| (c as char).to_digit(16);
            match (hex(bytes[i + 1]), hex(bytes[i + 2])) {
                (Some(hi), Some(lo)) => {
                    out.push((hi * 16 + lo) as u8);
                    i += 3;
                }
                _ => return Err(()),
            }
        } else {
            out.push(bytes[i]);
            i += 1;
        }
    }
    // STRICT UTF-8, because `decodeURIComponent` raises a URIError on a byte sequence that is not.
    String::from_utf8(out).map_err(|_| ())
}

/// `validPath(value)` — is this a rooted, clean path the relay may build an upstream URL from?
///
/// `//host` IS PROTOCOL-RELATIVE: it passes a "starts with /" test and then REPLACES THE ORIGIN in
/// `new URL(path, base)`. That is why the shape is refused here as well as after decoding.
pub fn valid_path(value: &str) -> bool {
    if value.is_empty()
        || !value.starts_with('/')
        || value.contains('\\')
        || value.contains('\0')
        || value.contains("..")
    {
        return false;
    }
    if value.starts_with("//") {
        return false;
    }
    let Ok(decoded) = decode_uri_component(value) else {
        return false;
    };
    decoded.starts_with('/')
        && !decoded.starts_with("//")
        && !decoded.contains('\\')
        && !decoded.contains("..")
        // `/[\0-\x1f]/` — the CONTROL CHARACTERS, and note the range stops at 0x1F: `\x7f` (DEL) is
        // not one of them, which the JavaScript suite pins with `/a\x7fb`.
        && !decoded.chars().any(|c| (c as u32) <= 0x1F)
}

/// `allowedRedirect(location, current)` — the redirect the relay will follow, or nothing.
///
/// **`github.com` EXACTLY.** `www.github.com` and `objects.githubusercontent.com` are both refused
/// here, where the github handler allows the asset hosts it needs. `https:` only, and a RELATIVE
/// location is resolved against the current URL, which is what `new URL(location, current)` does.
pub fn allowed_redirect(location: &str, current: &str) -> Option<String> {
    if location.is_empty() {
        return None;
    }
    let base = url::Url::parse(current).ok()?;
    let target = base.join(location).ok()?;
    if target.scheme() == "https" && target.host_str() == Some("github.com") {
        Some(target.to_string())
    } else {
        None
    }
}

// ── THE `api/github` GATE'S DECISIONS ───────────────────────────────────────────────────────────
//
// THE TWIN OF THE `api/git` GATE WITH THREE DELIBERATE DIFFERENCES, and each one is in the corpus:
//
//   * `safe_path` does NOT refuse `//` — the ORIGIN GUARD is what handles a protocol-relative path
//     here, and it is a separate decision (`upstream_url`).
//   * `redirect_target` allows SEVEN hosts rather than one, because this handler follows redirects to
//     GitHub's asset hosts (a release download lands on `objects.githubusercontent.com`).
//   * the two header allowlists are its own: it forwards conditional-request and range headers, and it
//     copies a different set back.

/// `UPSTREAMS` — the four route types and the origin each one means.
const UPSTREAMS: [(&str, &str); 4] = [
    ("web", "https://github.com"),
    ("raw", "https://raw.githubusercontent.com"),
    ("api", "https://api.github.com"),
    ("release", "https://github.com"),
];

