/// `safePath(value)` — the shape check WITHOUT the `//` refusal, because the origin guard is the thing
/// that catches a protocol-relative path in this handler.
pub fn safe_path(value: &str) -> bool {
    if value.is_empty() || !value.starts_with('/') {
        return false;
    }
    if value.contains('\\') || value.contains('\0') || value.contains("..") {
        return false;
    }
    let Ok(decoded) = decode_uri_component(value) else {
        return false;
    };
    decoded.starts_with('/')
        && !decoded.contains('\\')
        && !decoded.contains("..")
        && !decoded.chars().any(|c| (c as u32) <= 0x1F)
}

/// `parseRoute(value)` — `/type/rest` into the origin it means and the path to append.
///
/// **AND A PROTOTYPE KEY IS A CASE THIS PORT ANSWERS DIFFERENTLY ON PURPOSE.** `UPSTREAMS` is a plain
/// object in the TypeScript, so `parseRoute("/constructor/x")` finds `Object`'s constructor — a
/// FUNCTION — where a route type should be. Nothing downstream can use it: `upstreamUrl` calls
/// `new URL(base)` on it, throws, and the handler answers 400, which is exactly what an unknown type
/// answers. This port returns `None` for it, the corpus records the case with `baseIsString: false`,
/// and the test asserts the two verdicts agree where it matters — the observable outcome.
pub fn parse_route(value: Option<&str>) -> Option<(String, String)> {
    let value = value?;
    if value.is_empty() || !safe_path(value) {
        return None;
    }
    // `value.indexOf("/", 1)` — the first slash AFTER the leading one, so `/web` has no type at all.
    let slash = value[1..].find('/').map(|i| i + 1)?;
    let kind = &value[1..slash];
    let path = &value[slash..];
    let base = UPSTREAMS
        .iter()
        .find(|(name, _)| *name == kind)
        .map(|(_, base)| *base)?;
    if safe_path(path) {
        Some((base.to_string(), path.to_string()))
    } else {
        None
    }
}

/// `upstreamUrl(base, path)` — THE ORIGIN GUARD, and the reason it exists is a LIVE DEFECT: round 120
/// measured `GET https://v.saisi.online/api/git//example.com/` returning Example Domain's HTML with
/// the caller's GitHub token attached, because `new URL("//evil.example/x", "https://github.com")`
/// REPLACES THE ORIGIN. The per-handler shape checks test the path as a STRING; this tests the
/// RESOLVED ORIGIN, which is what decides where the request actually goes.
///
/// The error strings are the JavaScript's, because they reach the caller in a 400 body.
pub fn upstream_url(base: &str, path: &str) -> Result<String, String> {
    let want = url::Url::parse(base).map_err(|_| "uncomposable upstream path".to_string())?;
    let url = want
        .join(path)
        .map_err(|_| "uncomposable upstream path".to_string())?;
    if url.origin() != want.origin() {
        return Err(format!(
            "path escapes the upstream origin ({} != {})",
            url.origin().ascii_serialization(),
            want.origin().ascii_serialization()
        ));
    }
    Ok(url.to_string())
}

/// `copyRequestHeaders(request)` — the allowlist, truthiness, and `Headers` semantics.
pub fn copy_request_headers(headers: &Map<String, Value>) -> Vec<(String, String)> {
    copy_allowlisted(&REQUEST_HEADERS, headers)
}

/// `copyResponseHeaders(response)` — the same shape with the other list.
pub fn copy_response_headers(headers: &Map<String, Value>) -> Vec<(String, String)> {
    copy_allowlisted(&RESPONSE_HEADERS, headers)
}

fn copy_allowlisted(names: &[&str], headers: &Map<String, Value>) -> Vec<(String, String)> {
    let mut out: Vec<(String, String)> = Vec::new();
    for name in names {
        // `request.headers.get(name)` IS CASE-INSENSITIVE, and the harness passes a plain object.
        let found = headers
            .iter()
            .find(|(k, _)| k.to_lowercase() == *name)
            .map(|(_, v)| js_text(v));
        // `if (value)` — an empty header is not forwarded.
        if let Some(v) = found {
            if !v.is_empty() {
                out.push((name.to_string(), v));
            }
        }
    }
    combine(out)
}

/// `redirectTarget(location, currentUrl)` — an allowlisted `https:` host, resolved against the current
/// URL.
pub fn redirect_target(location: &str, current: &str) -> Option<String> {
    if location.is_empty() {
        return None;
    }
    let base = url::Url::parse(current).ok()?;
    let target = base.join(location).ok()?;
    if target.scheme() == "https"
        && target
            .host_str()
            .is_some_and(|h| ALLOWED_REDIRECT_HOSTS.contains(&h))
    {
        Some(target.to_string())
    } else {
        None
    }
}

// ── THE `api/zen` GATE: the path guard and the upstream request plan ────────────────────────────
//
// FIVE UPSTREAMS BEHIND ONE ROUTE, chosen by `?target=`, and the request half is where the rules are:
// the caller's key is required (BYOK, default-closed), an ABSENT target is `og` while an UNLISTED one
// is refused, and `og` authenticates by PATH — one credential scheme, chosen per endpoint.

/// `TARGETS` — the five upstreams, and each one's host is pinned by the JavaScript suite.
const TARGETS: [(&str, &str); 5] = [
    ("og", "https://opencode.ai/zen/go"),
    ("ds", "https://api.deepseek.com"),
    ("qw", "https://token-plan.ap-southeast-1.maas.aliyuncs.com"),
    ("or", "https://openrouter.ai/api"),
    ("cm", "https://api.commandcode.ai/provider"),
];

const ZEN_SAFE: [&str; 6] = [
    "accept",
    "accept-encoding",
    "accept-language",
    "anthropic-version",
    "content-type",
    "user-agent",
];

/// The conversation-id spellings a caller may send on an `og` request, in the order they are tried.
/// `x-opencode-session` is what zen/go expects; the others are what the gateway and DSH send.
const SESSION_SOURCE_HEADERS: [&str; 4] = [
    "x-opencode-session",
    "x-client-request-id",
    "session_id",
    "x-session-id",
];

/// `normalizeUpstreamPath(p)` — the traversal guard, and it is NOT the same rule as the other two
/// handlers':
///
///   * it decodes FIRST and returns the DECODED path, so `%2e%2e` is caught and the upstream receives
///     the plain form;
///   * a `\\` is refused because a WHATWG URL parser treats `\` as `/` for `https:`, so `\\host`
///     escapes the origin;
///   * an absolute URI or a scheme is refused — but a PROTOCOL-RELATIVE `//host` is NOT, because this
///     handler CONCATENATES (`base + path`) rather than resolving, so `//host` stays on the same
///     upstream and cannot move the origin;
///   * `..` must be a whole SEGMENT (`decoded.split("/").includes("..")`), where the git and github
///     guards refuse the substring.
pub fn normalize_upstream_path(p: &str) -> Option<String> {
    let decoded = decode_uri_component(p).ok()?;
    if !decoded.starts_with('/') {
        return None;
    }
    if decoded.contains('\\') {
        return None;
    }
    if decoded.contains("://") {
        return None;
    }
    // `/^[a-zA-Z][a-zA-Z0-9+.-]*:/` over `decoded.slice(1)` — a SCHEME in the tail, which is what
    // makes `/https:/evil.example` a refusal while `//evil.example` is not.
    if has_scheme_prefix(&decoded[1..]) {
        return None;
    }
    if decoded.contains('\0') || decoded.contains('\r') || decoded.contains('\n') {
        return None;
    }
    if decoded.split('/').any(|seg| seg == "..") {
        return None;
    }
    Some(decoded)
}

fn has_scheme_prefix(s: &str) -> bool {
    let mut chars = s.chars();
    match chars.next() {
        Some(c) if c.is_ascii_alphabetic() => {}
        _ => return false,
    }
    for c in chars {
        if c == ':' {
            return true;
        }
        if !(c.is_ascii_alphanumeric() || matches!(c, '+' | '.' | '-')) {
            return false;
        }
    }
    false
}

/// What the zen handler decided to do with a request.
#[derive(Debug, Clone, PartialEq)]
pub enum ZenPlan {
    /// `OPTIONS` short-circuits before the caller gate, like the other two handlers.
    Preflight,
    Refused {
        status: u16,
        error: String,
    },
    Send {
        url: String,
        headers: Vec<(String, String)>,
        send_body: bool,
    },
}

/// The request half of `handler(request)`.
///
/// THE TARGET CONTRACT, BOTH HALVES STATED (round 135): an ABSENT target is `og` — a documented
/// DEFAULT, not a fallback for something the caller asked for — while an UNLISTED target is refused,
/// because the caller's key would otherwise ride an upstream nobody vetted. The lookup is
/// `Object.hasOwn`, so `?target=constructor` is refused rather than finding `Object`'s constructor.
pub fn zen_upstream_plan(method: &str, request_url: &str, headers: &Map<String, Value>) -> ZenPlan {
    if method == "OPTIONS" {
        return ZenPlan::Preflight;
    }
    let get = |name: &str| -> Option<String> {
        headers
            .iter()
            .find(|(k, _)| k.to_lowercase() == name)
            .map(|(_, v)| js_text(v))
    };
    // `(x-api-key || authorization || "").trim()`, then a leading `bearer ` is stripped ONCE —
    // otherwise the reuse below sends `Bearer Bearer sk-…`.
    let raw_key = get("x-api-key")
        .filter(|v| !v.is_empty())
        .or_else(|| get("authorization").filter(|v| !v.is_empty()))
        .unwrap_or_default();
    let mut caller_key = raw_key.trim().to_string();
    if caller_key.to_lowercase().starts_with("bearer ") {
        caller_key = caller_key[7..].trim().to_string();
    }
    if caller_key.is_empty() {
        return ZenPlan::Refused {
            status: 401,
            error: "caller key required (x-api-key or Authorization)".to_string(),
        };
    }
    let query = url::Url::parse(request_url).ok();
    let param = |name: &str| -> Option<String> {
        query
            .as_ref()
            .and_then(|u| {
                u.query_pairs()
                    .find(|(k, _)| k == name)
                    .map(|(_, v)| v.to_string())
            })
            .filter(|v| !v.is_empty())
    };
    // `url.searchParams.get("target") || "og"` — an EMPTY target is the default too.
    let target = param("target").unwrap_or_else(|| "og".to_string());
    let Some((_, base)) = TARGETS.iter().find(|(name, _)| *name == target) else {
        return ZenPlan::Refused {
            status: 400,
            error: format!("unknown target: {target}"),
        };
    };
    let raw_path = param("path").unwrap_or_else(|| "/v1/messages".to_string());
    let Some(path) = normalize_upstream_path(&raw_path) else {
        return ZenPlan::Refused {
            status: 400,
            error: "invalid path".to_string(),
        };
    };
    let mut out: Vec<(String, String)> = Vec::new();
    for name in ZEN_SAFE {
        if let Some(v) = get(name) {
            if !v.is_empty() {
                out.push((name.to_string(), v));
            }
        }
    }
    if target == "og" {
        // EXACTLY ONE CREDENTIAL SCHEME, CHOSEN BY PATH: zen's two AI endpoints authenticate
        // differently — `/v1/messages` takes `x-api-key`, while `chat/completions` and the
        // OpenAI-format `/v1/responses` take `Authorization: Bearer`. Sending both leaked the key in
        // the scheme the endpoint does not use. Every other path keeps zen's native `x-api-key`.
        if path.contains("chat/completions") || path.contains("/v1/responses") {
            out.push(("authorization".to_string(), format!("Bearer {caller_key}")));
        } else {
            out.push(("x-api-key".to_string(), caller_key.clone()));
        }
        // THE SESSION HEADER IS og-ONLY, and the FIRST spelling that has a value wins.
        for name in SESSION_SOURCE_HEADERS {
            if let Some(v) = get(name) {
                if !v.is_empty() {
                    out.push(("x-opencode-session".to_string(), v.trim().to_string()));
                    break;
                }
            }
        }
    } else {
        out.push(("authorization".to_string(), format!("Bearer {caller_key}")));
    }
    if !out.iter().any(|(k, _)| k == "anthropic-version") {
        out.push(("anthropic-version".to_string(), "2023-06-01".to_string()));
    }
    out.retain(|(k, _)| k != "content-type");
    out.push(("content-type".to_string(), "application/json".to_string()));
    ZenPlan::Send {
        url: format!("{base}{path}"),
        headers: combine(out),
        send_body: matches!(method, "POST" | "PUT" | "PATCH"),
    }
}

// ── THE `api/gform` GATE'S DECISIONS: the body rewriter and its two helpers ─────────────────────
//
// THIS IS THE ONE HANDLER THAT REWRITES BYTES. Google's forms embed assets and scripts from eight
// hosts, and the relay rewrites every spelling of those URLs it can recognise into its own `/api/gform`
// URLs — because a form served through the relay must not fetch its own scripts direct-to-Google. It is
// DELIBERATELY LOSSY: a missed escape variant leaves one asset loading direct, which is visible in
// verification, where a half-matched rewrite would break the page.

const GFORM_UPSTREAMS: [(&str, &str); 8] = [
    ("gle", "https://forms.gle"),
    ("docs", "https://docs.google.com"),
    ("www", "https://www.google.com"),
    ("gstatic", "https://www.gstatic.com"),
    ("ssl-gstatic", "https://ssl.gstatic.com"),
    ("fontscss", "https://fonts.googleapis.com"),
    ("fonts", "https://fonts.gstatic.com"),
    ("usercontent", "https://lh3.googleusercontent.com"),
];

/// The script injected into every rewritten HTML page, verbatim from the JavaScript.
const SRI_NEUTRALIZER: &str = "\n<!-- SRI hashes do not survive byte rewriting; neutralize static + injected integrity -->\n<script>\n(function () {\n  try { Object.defineProperty(HTMLScriptElement.prototype, 'integrity', { configurable: true, get: function () { return ''; }, set: function () {} }); } catch (e) {}\n  new MutationObserver(function (ms) {\n    for (var i = 0; i < ms.length; i++) {\n      var ns = ms[i].addedNodes;\n      for (var j = 0; j < ns.length; j++) {\n        var el = ns[j];\n        if (!el || !el.querySelectorAll) continue;\n        var at = el.querySelectorAll('[integrity]');\n        for (var k = 0; k < at.length; k++) at[k].removeAttribute('integrity');\n      }\n    }\n  }).observe(document.documentElement || document, { subtree: true, childList: true });\n})();\n</script>";

/// `rewritable(contentType)` — is this response worth rewriting at all? Text, code and JSON are;
/// media, binary and an absent type are not.
pub fn rewritable(content_type: Option<&str>) -> bool {
    let Some(raw) = content_type else {
        return false;
    };
    let t = raw.to_lowercase();
    t.starts_with("text/")
        || t.contains("javascript")
        || t.contains("ecmascript")
        || t.contains("json")
}

/// `body.replace(/\s+integrity="[^"]*"/g, " ")` — every static `integrity` attribute, with its
/// surrounding whitespace, replaced by ONE SPACE.
///
/// Hand-rolled rather than regex, because this crate carries no regex engine and the pattern is four
/// clauses: whitespace (one or more), the literal `integrity="`, anything but a quote, a quote.
fn strip_integrity(body: &str) -> String {
    let bytes = body.as_bytes();
    let mut out = String::with_capacity(body.len());
    let mut i = 0;
    while i < bytes.len() {
        let ws_start = i;
        let mut j = i;
        while j < bytes.len() && bytes[j].is_ascii_whitespace() {
            j += 1;
        }
        if j > ws_start && body[j..].starts_with("integrity=\"") {
            let after = j + "integrity=\"".len();
            if let Some(close) = body[after..].find('"') {
                out.push(' ');
                i = after + close + 1;
                continue;
            }
        }
        // Not a match: copy this character and move on. (`is_ascii_whitespace` is `\s` for the ASCII
        // range, which is what the pattern's `\s` matches in this source.)
        let ch = body[i..].chars().next().unwrap_or(' ');
        out.push(ch);
        i += ch.len_utf8();
    }
    out
}

/// `rewriteBody(body, origin, isHtml)` — every recognised spelling of an upstream URL becomes a
/// `/api/gform` URL on THIS origin.
///
/// THE SIX SPELLINGS PER HOST ARE TRIED IN ORDER, escaped variants FIRST, so the plain `https://` form
/// can never half-match inside an escaped one: `https:\/\/host` (the JSON `\/` escape),
/// `https:\u002F\u002Fhost` and its lowercase twin, `https:\x2f\x2fhost` (obfuscated JS strings), the
/// plain form, and the protocol-relative `//host`.
///
/// `Err` is the JavaScript's throw: `new URL(origin)` on an origin that is not a URL.
pub fn rewrite_body(body: &str, origin: &str, is_html: bool) -> Result<String, String> {
    let mut out = body.to_string();
    if is_html {
        out = strip_integrity(&out);
        if let Some(head) = out.find("<head") {
            out.insert_str(head + 5, SRI_NEUTRALIZER);
        }
    }
    let origin_url = url::Url::parse(origin).map_err(|_| format!("invalid origin: {origin}"))?;
    let proxy_host = match origin_url.port() {
        Some(p) => format!("{}:{}", origin_url.host_str().unwrap_or(""), p),
        None => origin_url.host_str().unwrap_or("").to_string(),
    };
    let bs = '\\';
    for (key, base) in GFORM_UPSTREAMS {
        let host = url::Url::parse(base)
            .ok()
            .and_then(|u| u.host_str().map(|h| h.to_string()))
            .unwrap_or_default();
        let proxy = format!("{origin}/api/gform/{key}");
        let escaped = |esc: &str| proxy.split('/').collect::<Vec<_>>().join(esc);
        let pairs: [(String, String); 6] = [
            (
                format!("https:{bs}/{bs}/{host}"),
                escaped(&format!("{bs}/")),
            ),
            (
                format!("https:{bs}u002F{bs}u002F{host}"),
                escaped(&format!("{bs}u002F")),
            ),
            (
                format!("https:{bs}u002f{bs}u002f{host}"),
                escaped(&format!("{bs}u002f")),
            ),
            (
                format!("https:{bs}x2f{bs}x2f{host}"),
                escaped(&format!("{bs}x2f")),
            ),
            (format!("https://{host}"), proxy.clone()),
            (
                format!("//{host}"),
                format!("//{proxy_host}/api/gform/{key}"),
            ),
        ];
        for (from, to) in pairs {
            out = out.replace(&from, &to);
        }
    }
    Ok(out)
}

/// `setCookieValues(headers)` — EVERY `set-cookie`, because `Headers#get` returns only the first.
///
/// The JavaScript tries `getSetCookie()` and falls back to a `forEach` walk. The port takes both
/// shapes as arguments: the `getSetCookie()` values, and the entries the fallback would walk.
pub fn set_cookie_values(set_cookie: &[String], entries: &[(String, String)]) -> Vec<String> {
    if !set_cookie.is_empty() {
        return set_cookie.to_vec();
    }
    entries
        .iter()
        .filter(|(name, _)| name.to_lowercase() == "set-cookie")
        .map(|(_, value)| value.clone())
        .collect()
}

// ── WHAT THE RELAY ANSWERS WHEN THINGS GO WRONG ─────────────────────────────────────────────────
//
// Five handlers, four rules, and the differences between them are the point:
//
//   * **THE 5xx RULE IS A CONTRACT** (`proxies/README.md:13`): a 5xx gets GENERIC client text and the
//     detail stays in the log. `/api/proxy` used to stream the upstream's error body straight to the
//     caller — the provider's own words about a request it rejected, verbatim — which is the one thing
//     the documented contract says must not leave the worker.
//   * **THE STATUS IS THE UPSTREAM'S for the two API relays and a FIXED 502 for the three content
//     ones**, because "OpenRouter said 503" is a fact a client can act on, while a Google asset host
//     answering 503 says nothing about the relay's own fetch.
//   * **`no-store` ON ERRORS, and ONLY on the three content handlers.** An error response that a CDN
//     caches is an error served to the next caller, and the three that set it are the three that sit
//     behind one.
//   * **THE METHOD GATES DIFFER BY PROTOCOL**: git speaks smart-HTTP (GET/HEAD/POST), github and gform
//     are read-mostly (GET/HEAD, with gform taking a form POST), and the two API relays gate on nothing
//     but `OPTIONS` because their callers are programs.

/// The handler names this module knows — the five routes of the relay.
const HANDLERS: [&str; 5] = ["proxy", "zen", "git", "github", "gform"];

/// `method_allowed(handler, method)` — the gate each handler applies before anything else.
///
/// `OPTIONS` IS NOT LISTED, because every handler answers it BEFORE the gate: the two API relays
/// short-circuit to the CORS object, and the three content handlers do the same or refuse it as a
/// method like any other. The corpus drives the real handlers and pins which is which.
pub fn method_allowed(handler: &str, method: &str) -> Result<bool, String> {
    let allowed: &[&str] = match handler {
        // The API relays gate on NOTHING but `OPTIONS`: their callers are programs, and a method they
        // cannot use is answered by the upstream rather than here.
        "proxy" | "zen" => &[
            "GET", "HEAD", "POST", "PUT", "PATCH", "DELETE", "TRACE", "CONNECT",
        ],
        "git" => &["GET", "HEAD", "POST"],
        "github" => &["GET", "HEAD"],
        "gform" => &["GET", "HEAD", "POST"],
        other => return Err(format!("unknown handler: {other}")),
    };
    Ok(allowed.contains(&method))
}

/// The GENERIC text a 5xx carries out of the worker, or `None` where the handler does not have one.
///
/// **AND `git` IS THE ONE WITHOUT ONE, WHICH THE CORPUS FOUND AFTER THIS MODULE'S FIRST VERSION
/// ASSUMED OTHERWISE.** It answers a 5xx with the upstream's own body and status, verbatim — the git
/// protocol's errors are part of the exchange a client parses — while `github`, `gform`, `proxy` and
/// `zen` all replace the body with a sentence of their own, which is the documented contract
/// (`proxies/README.md:13`): the provider's words about a request it rejected must not leave the worker.
pub fn upstream_error_text(handler: &str) -> Result<Option<&'static str>, String> {
    match handler {
        "proxy" | "zen" => Ok(Some("Upstream unavailable")),
        "github" => Ok(Some("GitHub upstream unavailable")),
        "gform" => Ok(Some("Google upstream unavailable")),
        "git" => Ok(None),
        other => Err(format!("unknown handler: {other}")),
    }
}

/// The status a 5xx carries: **THE UPSTREAM'S, in every handler that rewrites the body**, which the
/// corpus pinned after the first version of this module guessed a fixed 502 for the content handlers.
/// `git` passes the upstream's status through with its body.
pub fn upstream_error_status(upstream_status: u16) -> u16 {
    upstream_status
}

/// The catch-all for an exception, which is NOT one sentence: the two API relays answer
/// `500 Internal error`, and the three content handlers answer **502 with their upstream sentence** —
/// because from their side an exception while fetching IS the upstream being unavailable.
pub fn catch_all(handler: &str) -> Result<(u16, &'static str), String> {
    match handler {
        "proxy" | "zen" => Ok((500, "Internal error")),
        "github" => Ok((502, "GitHub upstream unavailable")),
        "gform" => Ok((502, "Google upstream unavailable")),
        "git" => Ok((502, "GitHub upstream unavailable")),
        other => Err(format!("unknown handler: {other}")),
    }
}

/// The redirect cap: how many redirects a handler will follow before it refuses.
pub fn redirect_cap(handler: &str) -> Result<u32, String> {
    match handler {
        // git's is TIGHTER (3 against 5) and that is deliberate: a smart-HTTP clone's redirects are
        // `github.com` -> `github.com`, so a chain longer than a couple is a loop or a hijack.
        "git" => Ok(3),
        "github" | "gform" => Ok(5),
        other => Err(format!("unknown handler: {other}")),
    }
}
/// The `cache-control` an ERROR response carries, for the handlers that set one.
pub fn error_cache_control() -> &'static str {
    "no-store, max-age=0, must-revalidate"
}

/// Does this handler set `error_cache_control()` on its errors? The three that sit behind a CDN do; the
/// two API relays do not, and the corpus pins both directions.
pub fn sets_error_cache_control(handler: &str) -> Result<bool, String> {
    match handler {
        "git" | "github" | "gform" => Ok(true),
        "proxy" | "zen" => Ok(false),
        other => Err(format!("unknown handler: {other}")),
    }
}

/// Every handler this module knows, for a corpus that must exercise all of them.
pub fn handlers() -> &'static [&'static str] {
    &HANDLERS
}

// ── `proxies/summrise-relay/relay.mjs` — THE SECOND VPS PROCESS ─────────────────────────────────
//
// The plan names TWO Node processes on the VPS, and this crate is the axum target for both: `api-relay`
// (the public relay, whose `server/routing.mjs` and five handlers are already here) and
// `summrise-relay` — the LOCAL one an operator runs on their own machine, where a client's request is
// carried to the device over the agent's own long-poll (`/agent/pull` → the device → `/agent/answer`).
// What a client sees is the agent's HTTP surface, unchanged.
//
// THE TWO DECISIONS THAT ARE PURE are the token comparison and the routing table; the rest of that file
// is sockets, timers and queues.

/// `tokenOk(given, want)` — the agent's endpoints authenticate with a bearer token.
///
/// **IT IS TIMING-SAFE, AND THE PORT KEEPS THAT.** `timingSafeEqual` compares without leaking WHERE two
/// byte strings first differ, and a comparison that returns early leaks exactly that — which is the
/// whole attack on a shared secret. The length check comes first (it is not secret: the length of the
/// configured token is fixed and public to anyone who can count), and the bytes are then folded
/// together with no early exit.
///
/// **AND IT IS FAIL-CLOSED**: an empty `want` refuses EVERY caller, because a relay configured without a
/// token must not be a relay anyone can drive.
pub fn token_ok(given: &str, want: &str) -> bool {
    if want.is_empty() {
        return false;
    }
    let a = given.as_bytes();
    let b = want.as_bytes();
    if a.len() != b.len() {
        return false;
    }
    let mut diff = 0u8;
    for i in 0..a.len() {
        diff |= a[i] ^ b[i];
    }
    diff == 0
}

/// `routeOf(pathname, method)` — the relay's whole routing table.
///
/// THE ORDER IS THE RULE: the agent's two endpoints first (the second only for a POST, so a GET to
/// `/agent/answer` falls through to the device like any other path), then the health probe, then
/// everything else is forwarded.
pub fn relay_route(pathname: &str, method: &str) -> &'static str {
    if pathname == "/agent/pull" {
        return "agent-pull";
    }
    if pathname == "/agent/answer" && method == "POST" {
        return "agent-answer";
    }
    if pathname == "/healthz" {
        return "healthz";
    }
    "forward"
}

/// The body cap: a request larger than this is answered 413 rather than buffered.
pub fn max_body() -> usize {
    8 * 1024 * 1024
}

/// How long an agent's long-poll is parked before it is answered 204 and dropped.
pub fn long_poll_ms() -> u64 {
    25_000
}

