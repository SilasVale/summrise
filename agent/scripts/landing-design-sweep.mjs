// landing-design-sweep — the LANDING, measured as RENDERED.
//
// WHY IT EXISTS (round 81). Three of the four surfaces were measured as rendered: the panel through a generated
// harness, the console through a build of its own checkout. The landing was measured as TEXT — `landing-check` reads
// `page.js`'s own values and asserts contrast, exactly one h1 and a 320px reflow — and a static read cannot see the
// cascade as painted, the state that replaces the installer button when a release publishes none, focus order, or a
// press. This serves the page the WORKER serves, in BOTH installer states and both colour schemes, and measures it
// with the probes and the judge the other two surfaces use.
//
//   node agent/scripts/landing-design-sweep.mjs --emit > /tmp/landing.js   (run it where a browser is)
//   node agent/scripts/landing-design-sweep.mjs --judge <report.json>
//
// THE PAGE IS GENERATED BY CALLING PAGE(), the entry point `index/src/index.js` serves and the index tests call, so
// there is no second renderer to drift from the first. `--emit` renders both states into the output directory and
// copies the brand assets beside them; the emitted script serves that directory and nothing else.
import { cpSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join } from "node:path";
import { markCoverageNotes } from "./lib/design-sweep.mjs";
import { fileURLToPath } from "node:url";
import { PAGE } from "../../index/src/page.js";
import { pageChecks, judgeReport, reportSummary, UNSTYLED_SOURCE, focusPass, pressPass, idlePass, motionPass, TARGETS_SOURCE, pressDelta, discoverPressTargets } from "./lib/design-sweep.mjs";
import { bundleSweep } from "./lib/sweep-bundle.mjs";
import { PROBE_SOURCE } from "./lib/contrast-probe.mjs";

const HERE = fileURLToPath(new URL(".", import.meta.url));
const REPO = join(HERE, "..", "..");
const OUT = process.env.VALE_LANDING_OUT || "/tmp/vale-landing";
const PASSES = (process.argv.find((a) => a.startsWith("--passes=")) || "").slice("--passes=".length).split(",").filter(Boolean);
const mode = process.argv[2] || "";

/** The landing's CSS, cropped out of the module that ships it. It THROWS rather than returning an empty string: the
 *  mark-coverage note reads a sheet to answer "which states does this declare", and an empty sheet answers "none" —
 *  which is indistinguishable from a clean surface. (Round 51 wrote this call without the helper, the judge threw at
 *  runtime, and the local check that missed it read the OUTPUT instead of the exit code — the rule this repository's
 *  AGENTS.md states in bold, broken by the loop that quotes it.) */
function landingStyles() {
  const src = readFileSync(new URL("../../index/src/page.js", import.meta.url), "utf8");
  const m = /<style>([\s\S]*?)<\/style>/.exec(src);
  if (!m) {
    throw new Error("the landing's <style> block was not found — the coverage note would be reading an empty sheet and reporting a clean surface");
  }
  return m[1];
}

// THE TWO STATES A RELEASE CAN PRODUCE, and the reason a rendered arm is worth its cost. When a release publishes no
// installer the page swaps the primary button for a hint — a different element, a different size, a different
// contrast question — and nothing has ever looked at it in a browser.
const CONSOLE_URL = "https://ai.saisi.online";
const INSTALLER_URL = "https://agent.saisi.online/vale-agent/vale-agent-latest.tgz";
const SETUP_URL = "https://agent.saisi.online/vale-agent/ValeAgent-Setup.exe";
const PAGES = [
  ["installer", PAGE(CONSOLE_URL, INSTALLER_URL, SETUP_URL)],
  ["npm-only", PAGE(CONSOLE_URL, INSTALLER_URL, null)],
];

function render() {
  mkdirSync(OUT, { recursive: true });
  for (const [label, html] of PAGES) writeFileSync(join(OUT, label + ".html"), html);
  // `public/` is what the worker serves beside the page (brand art, headers). Copied rather than referenced so the
  // emitted script can serve ONE directory wherever it runs.
  const brand = join(REPO, "index", "public", "brand");
  if (existsSync(brand)) cpSync(brand, join(OUT, "brand"), { recursive: true });
  return PAGES.map(([label]) => label);
}

// ONE ROOT, BOTH ENDS (round 77's lesson): the stamp is baked from the entry the RUN will serve, and the default is
// the device path so a delivered copy is compared against the copy it was emitted for.
const ROOT = process.env.VALE_SWEEP_ROOT || "C:\\ProgramData\\Vale\\pwout\\landing";
const stampOf = (file) => {
  try {
    const b = readFileSync(file);
    return { bytes: b.length, sha: createHash("sha256").update(b).digest("hex").slice(0, 12) };
  } catch (e) {
    return { bytes: -1, sha: "(unreadable)" };
  }
};
function browserScript() {
  // READ AFTER THE RENDER, not at module load (round 82's second CI run). The stamp was computed before --emit had
  // written the page, so it baked as {bytes: -1, sha: "(unreadable)"} and every run reported its own entry as stale
  // — a true sentence about two artefacts and a useless one about a commit. The call order is the fix: render()
  // runs first in the --emit branch, and the stamp is read here, from the file that branch just wrote.
  const LOCAL_STAMP = stampOf(join(OUT, "installer.html"));
  // THE PAYLOAD IS A REAL MODULE NOW (round 266). It used to be this file's own template literal, with the probe,
  // the six passes and the page checks interpolated as text — which is why a backtick in a pass's comment could end
  // this file mid-parse, and why `assertEmbedded` existed to check by substring that a borrowed helper had also been
  // spliced. lib/sweep/landing-run.cjs is ordinary code; what varies per run arrives as the generated pieces module
  // beside it, and the assembler compiles the result before returning it.
  const pieces = piecesSource(LOCAL_STAMP);
  // MODULE IDS ARE NORMALISED PATHS, no leading "./" (the resolver collapses "." segments, so an id spelled one way
  // and required another would be two modules — measured: the first run of this bundler refused "./pieces.cjs"
  // because the id carried a prefix the resolver had already stripped).
  const { code } = bundleSweep({
    entry: "landing-run.cjs",
    modules: {
      "landing-run.cjs": readFileSync(join(HERE, "lib", "sweep", "landing-run.cjs"), "utf8"),
      "pieces.cjs": pieces,
    },
  });
  return code;
}

/** The run-varying pieces, as a MODULE rather than as interpolations in a template literal. The passes are real
 *  values here (`fn.toString()` at emit time, declarations in the generated module) and they all land in ONE module
 *  body, which is what makes a helper that a pass calls by name resolve: `pressPass` calls `discoverPressTargets`,
 *  which used to be a hand-listed "must also be embedded" and is now simply in scope. */
function piecesSource(LOCAL_STAMP) {
  const helpers = { focusPass, pressDelta, discoverPressTargets, pressPass, idlePass, motionPass };
  const decls = Object.entries(helpers).map(([name, fn]) => `const ${name} = ${fn.toString()};`).join("\n");
  // THE PAGE CHECKS ARE STILL SOURCE TEXT, and this is the honest boundary of this slice: pageChecks() is a
  // source-text generator (it substitutes a root selector into a template), so it is evaluated ONCE here into real
  // string values. Converting the checks themselves into functions that take the root selector as an argument is the
  // next slice, and it is the same move this round made for the landing's payload.
  const checks = new Function(pageChecks("body") + "\nreturn { SURFACE, NAMES, REFLOW };")();
  return `${decls}
module.exports = {
  config: ${JSON.stringify({ root: ROOT, reportPath: "C:\\ProgramData\\Vale\\pwout\\landing-sweep.json", passes: PASSES, expectedEntry: LOCAL_STAMP })},
  probe: ${JSON.stringify(PROBE_SOURCE)},
  unstyled: ${JSON.stringify(UNSTYLED_SOURCE)},
  targets: ${JSON.stringify(TARGETS_SOURCE)},
  checks: ${JSON.stringify(checks)},
  passes: { ${Object.keys(helpers).join(", ")} },
};
`;
}

function judge(file) {
  const report = JSON.parse(readFileSync(file, "utf8"));
  // THE SHARED CLAUSES, NOT A COPY OF THEM. The first version of this function re-implemented names, marks and
  // unstyled by hand — and got the target axis wrong on its first CI run, because `undersized` in that probe is a
  // COUNT and the list is `distinct`. Duplicating a clause costs exactly what duplication costs; the console's judge
  // had the right shape all along (it calls judgeReport and adds only what is its own), and this does the same.
  //
  // The press clause is NOT repeated here: the shared judge already fails a pass that measured nothing ("a press
  // pass that pressed nothing proves nothing"), and my copy of it made the same finding twice. Pruned.
  //
  // `navless`: the landing has no navigation BY DESIGN — it is one page with steps, not an application — and the
  // landmark clause would otherwise read that as a defect on every surface.
  //
  // `unstyledFloor`: the shared floor is 100 because the panel and the console each style hundreds of classes. The
  // landing is ONE PAGE with 22, and the floor's purpose is to make a broken collector loud — so 15 is the number
  // that does that job here without failing a page that is simply small. Measured: 22.
  const findings = judgeReport(report, { navless: ["installer", "npm-only"], unstyledFloor: 15 });
  for (const t of report.themeChecks || []) {
    // READ OFF THE PAGE, not off the instruction: the sweep asks the browser for its colour-scheme media query and
    // the report carries the answer, so a page that ignored the emulation cannot pass as the scheme it was asked for.
    if (typeof t.scheme === "boolean" && t.scheme !== (t.intended === "dark")) {
      findings.push(`scheme: ${t.page} was rendered for "${t.intended}" but the page reports prefers-color-scheme: dark = ${t.scheme}`);
    }
  }
  for (const t of report.targets || []) {
    for (const u of t.distinct || []) {
      if (!u.passesBySpacing) findings.push(`target size (${t.page}): ${u.sel} is ${u.w}x${u.h} with its nearest neighbour ${u.nearest}px away — 2.5.8 wants 24x24 or 24px of spacing ("${u.text}")`);
    }
  }
  const check = report.entryCheck || {};
  if (check.stale) findings.push(`the delivered entry is ${check.bytes} bytes / sha ${check.sha} but this sweep was emitted against ${check.expected && check.expected.bytes} / ${check.expected && check.expected.sha} — every measurement below is of a stale build`);
  // THE STATES THIS SHEET DECLARES AND THIS RUN NEVER PAINTED (round 51 of the standing goal), the third and last
  // surface to get the queue the panel has had since round 32. The landing's styles are not a sheet of their own: they
  // are a `<style>` block inside `index/src/page.js`, so they are cropped out of the module — the same extraction
  // `feedback-check.mjs` and `landing-check.mjs` already use, and it THROWS rather than measuring an empty string,
  // because a note about zero declared families reads exactly like a clean surface.
  for (const line of markCoverageNotes(landingStyles(), report)) console.log(line);
  console.log(reportSummary("landing", report));
  if (!findings.length) {
    console.log("landing design sweep OK: nothing above found a defect");
    return 0;
  }
  console.error(`\n${findings.length} finding(s):\n  ` + findings.join("\n  "));
  return 1;
}

if (mode === "--emit") {
  const labels = render();
  console.error(`landing: rendered ${labels.join(", ")} into ${OUT}`);
  const out = browserScript();
  // THE BUNDLER COMPILED IT ALREADY (bundleSweep's last act), which is the guard THIS emitter never had — the other
  // four had a hand-copied `new Function` and this one printed its ~79 KB script to stdout without ever asking
  // whether it parsed. What replaces `assertEmbedded` is the pieces being a real module: their names are in scope by
  // construction, not by a substring test that a CALL could satisfy.
  process.stdout.write(out);
} else if (mode === "--judge") {
  const file = process.argv[3];
  if (!file) {
    console.error("usage: landing-design-sweep.mjs --judge <report.json>");
    process.exit(2);
  }
  process.exit(judge(file));
} else {
  console.error(readFileSync(fileURLToPath(import.meta.url), "utf8").split("\n").slice(1, 14).join("\n"));
  console.error("\nusage: landing-design-sweep.mjs --emit | --judge <report.json>");
  process.exit(2);
}